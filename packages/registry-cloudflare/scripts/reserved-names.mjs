// Writes a migration that reserves the names the public registry keeps back until an administrator
// approves someone for one (README "Reserved names"). They are Velt's own names, and npm's
// high-impact packages and scopes (the `npm-high-impact` package, MIT): Velt users know those
// names from npm, and `velt` installs npm packages too. 0002_reserved_names.sql is its first run.
//
//   npm pack npm-high-impact && tar xzf npm-high-impact-*.tgz
//   node scripts/reserved-names.mjs package 0003_reserved_names.sql > src/migrations/0003_reserved_names.sql
//
// To update the list, write the next numbered migration, and never edit one already applied: D1
// runs each migration once. Rows go in with `INSERT OR IGNORE`, so names already reserved keep
// their holder and reason. Only names a Velt package can have are kept (lowercase words joined by
// `-` or `_`; a `.` in an npm name, as in `socket.io`, read as `_`), each under registry-core's key:
// its `normalizedName` (`-` as `_`), and `@scope` for a scope.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const [dir, migration] = process.argv.slice(2);
if (!dir || !migration) {
  console.error("usage: node scripts/reserved-names.mjs <npm-high-impact dir> <migration file name>");
  process.exit(2);
}
const { version } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
const { top } = await import(pathToFileURL(join(dir, "lib/top.js")).href);

/** Velt's own names and scopes. */
const OWN = [
  "veltlang", "velt-lang", "stdlib", "core", "prelude", "registry", "admin", "administrator",
  "root", "api", "www", "login", "signup", "help", "support", "security", "official",
  "@velt", "@veltlang", "@velt-lang", "@std", "@registry", "@admin",
];

const WORD = /^[a-z][a-z0-9]*([-_][a-z0-9]+)*$/;

/** `name`'s key (a `.` read as `_`), or null when no Velt package or scope can be named so. */
function keyOf(name) {
  const word = (w) => {
    const v = w.replaceAll(".", "_");
    return WORD.test(v) ? v.replaceAll("-", "_") : null;
  };
  if (name.startsWith("@")) {
    const scope = word(name.slice(1).split("/")[0]);
    return scope === null ? null : `@${scope}`;
  }
  return word(name);
}

const reasons = new Map();
for (const name of OWN) reasons.set(keyOf(name), "a name of Velt's own");
for (const name of top) {
  const key = keyOf(name);
  if (key !== null && !reasons.has(key)) {
    reasons.set(key, key.startsWith("@") ? "a well-known npm scope" : "a well-known npm package");
  }
}

const rows = [...reasons].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const out = [
  `-- ${migration}: generated by scripts/reserved-names.mjs from npm-high-impact ${version}. Do not`,
  `-- edit it once applied: write the next numbered migration instead.`,
  `-- ${rows.length} names and scopes kept back until an administrator approves someone for one.`,
];
const CHUNK = 500;
for (let i = 0; i < rows.length; i += CHUNK) {
  const values = rows.slice(i, i + CHUNK).map(([key, reason]) => `  ('${key}', '${reason.replaceAll("'", "''")}')`);
  out.push(`INSERT OR IGNORE INTO reserved_names (key, reason) VALUES\n${values.join(",\n")};`);
}
process.stdout.write(`${out.join("\n")}\n`);
