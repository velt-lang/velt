#!/usr/bin/env python3
"""Writes std/crypto/x25519_base_table.velt: multiples of the Edwards25519 base point B for X25519's
fixed-base multiplication (std/crypto/x25519_base.velt, #2955), as ref10's `ge_scalarmult_base`
uses them. Table i (0..31) holds (j + 1) * 256^i * B for j = 0..7, each in the precomputed form
(y + x, y - x, 2 d x y) of affine Edwards coordinates, each element as five 51-bit limbs (radix
2^51, std/crypto/field25519.velt), fully reduced: 15 limbs a point, entry (i, j) at (8 i + j) * 15.

    python3 scripts/gen-x25519-base-table.py > std/crypto/x25519_base_table.velt
"""

P = 2**255 - 19
D = -121665 * pow(121666, P - 2, P) % P
L = 2**252 + 27742317777372353535851937790883648493
# The base point: y = 4/5, x the even root.
BY = 4 * pow(5, P - 2, P) % P


def recover_x(y):
    xx = (y * y - 1) * pow(D * y * y + 1, P - 2, P) % P
    x = pow(xx, (P + 3) // 8, P)
    if (x * x - xx) % P != 0:
        x = x * pow(2, (P - 1) // 4, P) % P
    assert (x * x - xx) % P == 0
    return x if x % 2 == 0 else P - x


B = (recover_x(BY), BY)


def add(p1, p2):
    (x1, y1), (x2, y2) = p1, p2
    t = D * x1 * x2 * y1 * y2 % P
    x3 = (x1 * y2 + x2 * y1) * pow(1 + t, P - 2, P) % P
    y3 = (y1 * y2 + x1 * x2) * pow(1 - t, P - 2, P) % P
    return (x3, y3)


def limbs(v):
    return [(v >> (51 * k)) & (2**51 - 1) for k in range(5)]


def ladder_u(k):
    """RFC 7748's X25519 of a clamped scalar with u = 9, for the self-check."""
    x1, x2, z2, x3, z3, swap = 9, 1, 0, 9, 1, 0
    for t in reversed(range(255)):
        bit = (k >> t) & 1
        swap ^= bit
        if swap:
            x2, x3, z2, z3 = x3, x2, z3, z2
        swap = bit
        a, b = (x2 + z2) % P, (x2 - z2) % P
        aa, bb = a * a % P, b * b % P
        e = (aa - bb) % P
        c, d = (x3 + z3) % P, (x3 - z3) % P
        da, cb = d * a % P, c * b % P
        x3, z3 = (da + cb) ** 2 % P, x1 * (da - cb) ** 2 % P
        x2, z2 = aa * bb % P, e * (aa + 121665 * e) % P
    if swap:
        x2, z2 = x3, z3
    return x2 * pow(z2, P - 2, P) % P


def main():
    words = []
    base = B
    for _ in range(32):
        point = None
        for _ in range(8):
            point = base if point is None else add(point, base)
            x, y = point
            words += limbs((y + x) % P) + limbs((y - x) % P) + limbs(2 * D * x * y % P)
        for _ in range(8):
            base = add(base, base)
    # Self-check: the Edwards multiple of B maps to the ladder's u.
    k = (2**254) | (0x1234567890ABCDEF << 3)
    acc, q, kk = None, B, k
    while kk:
        if kk & 1:
            acc = q if acc is None else add(acc, q)
        q = add(q, q)
        kk >>= 1
    assert (1 + acc[1]) * pow(1 - acc[1], P - 2, P) % P == ladder_u(k)
    print(
        "// velt/crypto (internal): multiples of the Edwards25519 base point B for X25519's fixed-base\n"
        "// multiplication (std/crypto/x25519_base.velt): table i holds (j + 1) * 256^i * B for\n"
        "// j = 0..7 as (y + x, y - x, 2 d x y), five 51-bit limbs each, entry (i, j) at (8 i + j) * 15.\n"
        "// A module constant that is an array of number literals, so it is stored once in the program\n"
        "// and read where it is.\n"
        "// Generated by scripts/gen-x25519-base-table.py; edit that and run it again.\n"
        "\n"
        "/** (j + 1) * 256^i * B for the 32 tables i and j = 0..7 (see the file's comment). */"
    )
    print("export const X25519_BASE: u64[] = [")
    for w in words:
        print(f"  0x{w:013x},")
    print("];")


main()
