#!/usr/bin/env python3
"""Writes std/compress/inflate/crc_table.vlt: gzip's CRC-32 (RFC 1952 §8, the reflected polynomial
0xEDB88320) as slicing-by-8 tables, table `k` at `k * 256`: table 0 is the byte-at-a-time table,
and table `k` advances table `k - 1`'s value by one more zero byte.

    python3 scripts/gen-crc32-table.py > std/compress/inflate/crc_table.vlt
"""

POLY = 0xEDB88320

t0 = []
for n in range(256):
    c = n
    for _ in range(8):
        c = (c >> 1) ^ POLY if c & 1 else c >> 1
    t0.append(c)
tables = [t0]
for k in range(1, 8):
    prev = tables[-1]
    tables.append([(prev[n] >> 8) ^ t0[prev[n] & 0xFF] for n in range(256)])

print(
    "// velt/compress (internal): gzip's CRC-32 table (RFC 1952 §8). A module constant that is an\n"
    "// array of number literals, so it is stored once in the program and read where it is.\n"
    "// Generated by scripts/gen-crc32-table.py; edit that and run it again.\n"
    "\n"
    "/** CRC-32 (reflected polynomial 0xEDB88320) slicing-by-8 tables: table `k` at `k * 256`. */\n"
    "export const CRC_TABLE: u32[] = [\n"
    + "".join(f"  {x},\n" for t in tables for x in t)
    + "];",
)
