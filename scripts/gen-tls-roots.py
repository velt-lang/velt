#!/usr/bin/env python3
"""Writes std/net/tls/x509/roots_table.velt: the trust anchors of the TLS client in Velt, which
are those of the webpki-roots crate (Mozilla's set of roots trusted for TLS servers, from the
CCADB).

The input is webpki-roots' src/lib.rs at the version below (from crates.io): its
`TLS_SERVER_ROOTS` holds, for each root, the subject Name's contents, the SubjectPublicKeyInfo's
contents and the nameConstraints' contents (or none). The script refuses a file whose SHA-256 is
not the one pinned below; to update the roots, set the new version and hash here and run it
again, and review the difference in the table's names.

    python3 scripts/gen-tls-roots.py ~/.cargo/registry/src/*/webpki-roots-1.0.9/src/lib.rs \
        > std/net/tls/x509/roots_table.velt
"""

import hashlib
import re
import sys

VERSION = "1.0.9"
SHA256 = "581232b6fb8d5b8df315d34c798099ee759cb4930ffed77c331e7b38fed82b15"

ESCAPES = {"n": 10, "r": 13, "t": 9, "\\": 92, "0": 0, '"': 34, "'": 39}


def byte_string(literal):
    """The bytes of a Rust byte-string literal's contents."""
    out = bytearray()
    i = 0
    while i < len(literal):
        c = literal[i]
        if c != "\\":
            out.append(ord(c))
            i += 1
        elif literal[i + 1] == "x":
            out.append(int(literal[i + 2 : i + 4], 16))
            i += 4
        else:
            out.append(ESCAPES[literal[i + 1]])
            i += 2
    return bytes(out)


LITERAL = r'b"((?:[^"\\]|\\.)*)"'
ANCHOR = re.compile(
    r"TrustAnchor \{\s*subject: Der::from_slice\(" + LITERAL + r"\),\s*"
    r"subject_public_key_info: Der::from_slice\(" + LITERAL + r"\),\s*"
    r"name_constraints: (?:None|Some\(Der::from_slice\(" + LITERAL + r"\)\))\s*\}",
    re.S,
)


def main():
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} <webpki-roots {VERSION}'s src/lib.rs>")
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{sys.argv[1]} is not webpki-roots {VERSION}'s lib.rs: SHA-256 {digest}")
    text = data.decode()
    anchors = [
        (byte_string(s), byte_string(k), byte_string(c) if c is not None else b"")
        for s, k, c in ANCHOR.findall(text)
    ]
    if len(anchors) != text.count("TrustAnchor {"):
        sys.exit("an anchor did not parse")
    blob = bytearray()
    ends = []
    for subject, spki, constraints in anchors:
        for part in (subject, spki, constraints):
            blob += part
            ends.append(len(blob))
    total = len(blob)
    blob += bytes(-len(blob) % 8)
    words = [int.from_bytes(blob[i : i + 8], "little") for i in range(0, len(blob), 8)]
    out = [
        "// velt/net (internal): the trust anchors of the TLS client: the roots Mozilla trusts for TLS",
        f"// servers (the CCADB's list), as the webpki-roots crate {VERSION} has them. Each anchor is",
        "// three DER values one after the other in `ROOT_BYTES`: the subject Name's contents, the",
        "// SubjectPublicKeyInfo's contents and the nameConstraints' contents (empty for none);",
        "// `ROOT_ENDS` has where each of the three ends.",
        "// Generated by scripts/gen-tls-roots.py; edit that and run it again.",
        "",
        "/** How many anchors there are. */",
        f"export const ROOT_COUNT: usize = {len(anchors)};",
        "",
        "/** The bytes used of `ROOT_BYTES`. */",
        f"export const ROOT_BYTES_LENGTH: usize = {total};",
        "",
        "/** The anchors' values, eight bytes a word, the first byte lowest. */",
        "export const ROOT_BYTES: u64[] = [",
    ]
    out += [f"  0x{w:016x}," for w in words]
    out += [
        "];",
        "",
        "/** Three offsets an anchor: the ends of its subject, its key and its name constraints. */",
        "export const ROOT_ENDS: u32[] = [",
    ]
    out += [f"  {e}," for e in ends]
    out += ["];"]
    print("\n".join(out))


main()
