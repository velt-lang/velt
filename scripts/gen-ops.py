#!/usr/bin/env python3
# Generates `velt/ops` (std/ops/*.vlt): one interface per operator method (design
# docs/internals/design/operators.md) and the operator methods of the number types and
# `string`, so that generic code bounded by the interfaces (`T extends Add<T>`) runs on them.
# Each number method is the built-in operator itself (`return this + other;`), so it means
# exactly what the operator means, overflow included. To change them, change this script and
# run it from the repository root, then `velt fmt` the files:
#
#   python3 scripts/gen-ops.py && velt fmt std/ops/*.vlt
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "std", "ops")
HEADER = "// Generated by scripts/gen-ops.py: change the script, not this file.\n"

# (interface, key, operator, doc)
BINARY = [
    ("Add", "add", "+", "addition"), ("Sub", "sub", "-", "subtraction"),
    ("Mul", "mul", "*", "multiplication"), ("Div", "div", "/", "division"),
    ("Rem", "rem", "%", "remainder"), ("Pow", "pow", "**", "exponentiation"),
    ("BitAnd", "bitAnd", "&", "bitwise and"), ("BitOr", "bitOr", "|", "bitwise or"),
    ("BitXor", "bitXor", "^", "bitwise exclusive or"), ("Shl", "shl", "<<", "left shift"),
    ("Shr", "shr", ">>", "right shift"), ("UShr", "ushr", ">>>", "unsigned right shift"),
]
UNARY = [("Neg", "neg", "-", "negation"), ("BitNot", "bitNot", "~", "bitwise not")]

INTS = ["i8", "i16", "i32", "i64", "isize", "u8", "u16", "u32", "u64", "usize"]
FLOATS = ["f32", "f64"]


def interfaces():
    out = [
        "// velt/ops (internal): the interfaces of the operator methods. Programs import them from",
        "// `velt/ops`.",
        "//",
        "// `a + b` on a class, struct or vector calls its method `[Symbol.add](other)` (design",
        "// operators.md). A type with the method implements the interface without an `implements`",
        "// clause, so generic code bounded by one (`T extends Mul<T>`) can use the operator.",
        "//",
        HEADER.rstrip(),
        "",
    ]
    for iface, key, op, doc in BINARY:
        out += [
            f"/** A type with `a {op} b` ({doc}) for a right operand of type `R`, giving an `O`. */",
            f"export interface {iface}<R, O = R> {{",
            f"  /** `this {op} other`. */",
            f"  [Symbol.{key}](other: R): O;",
            "}",
            "",
        ]
    for iface, key, op, doc in UNARY:
        out += [
            f"/** A type with `{op}a` ({doc}), giving an `O`. */",
            f"export interface {iface}<O> {{",
            f"  /** `{op}this`. */",
            f"  [Symbol.{key}](): O;",
            "}",
            "",
        ]
    for iface, key, op, doc in BINARY:
        out += [
            f"/** A type with `a {op}= b` that changes `a` in place, for a right operand of type `R`. */",
            f"export interface {iface}Assign<R> {{",
            f"  /** `this {op}= other`, changing `this`. */",
            f"  [Symbol.{key}Assign](other: R): void;",
            "}",
            "",
        ]
    out += [
        "/** A type with `a[i]` for an index of type `K`, giving a `V`. */",
        "export interface Index<K, V> {",
        "  /** The element at `i`. */",
        "  [Symbol.index](i: K): V;",
        "}",
        "",
        "/** A type with `a[i] = v` for an index of type `K` and a value of type `V`. */",
        "export interface SetIndex<K, V> {",
        "  /** Sets the element at `i` to `v`. */",
        "  [Symbol.setIndex](i: K, v: V): void;",
        "}",
        "",
        "/**",
        " * The arithmetic of a number-like type: `+`, `-`, `*`, `/` and unary `-`, each giving a `T`.",
        " * Every number type, `velt/math`'s `BigInt` and the float vectors of `velt/simd` have it.",
        " */",
        "export interface Arithmetic<T> extends Add<T>, Sub<T>, Mul<T>, Div<T>, Neg<T> {}",
        "",
    ]
    return "\n".join(out)


def numbers(what, types, with_string):
    out = [
        f"// velt/ops (internal): the operator methods of the {what}, so that generic code bounded",
        "// by `velt/ops`' interfaces runs on them. Each is the built-in operator itself, which",
        "// generic code compiles to after inlining.",
        "//",
        HEADER.rstrip(),
        "",
    ]
    for t in types:
        is_float = t in FLOATS
        signed = t.startswith("i") or is_float
        bitwise = not is_float or t == "f64"
        out.append(f"extend {t} {{")
        for _, key, op, _ in BINARY:
            if op in ["&", "|", "^", "<<", ">>", ">>>"] and not bitwise:
                continue
            out.append(f"  /** `this {op} other`. */")
            out.append(f"  [Symbol.{key}](other: {t}): {t} {{")
            out.append(f"    return this {op} other;")
            out.append("  }")
        if signed:
            out += [f"  /** `-this`. */", f"  [Symbol.neg](): {t} {{", "    return -this;", "  }"]
        if bitwise:
            out += [f"  /** `~this`. */", f"  [Symbol.bitNot](): {t} {{", "    return ~this;", "  }"]
        out += ["}", ""]
    if not with_string:
        return "\n".join(out)
    out += [
        "extend string {",
        "  /** `this + other`, the strings joined. */",
        "  [Symbol.add](other: string): string {",
        "    return this + other;",
        "  }",
        "}",
        "",
    ]
    return "\n".join(out)


def index():
    names = [b[0] for b in BINARY] + [u[0] for u in UNARY] + [b[0] + "Assign" for b in BINARY]
    names += ["Index", "SetIndex", "Arithmetic"]
    out = [
        "// velt/ops: the interfaces of the operator methods, for generic code that uses operators",
        "// (https://veltlang.com/docs/std/ops/):",
        "//",
        '//   import type { Arithmetic } from "velt/ops";',
        "//   function dot<T extends Arithmetic<T>>(a: T[], b: T[], zero: T): T { … }",
        "//",
        "// Importing it also gives the number types and `string` their operator methods.",
        "//",
        HEADER.rstrip(),
        "",
        "export {",
    ]
    out += [f"  {n}," for n in names]
    out += ['} from "velt/ops/operators";']
    out += [f'import "velt/ops/{m}";' for m in ["signed", "unsigned", "floats"]]
    out += [""]
    return "\n".join(out)


FILES = [
    ("operators.vlt", interfaces()),
    ("signed.vlt", numbers("signed integer types", INTS[:5], False)),
    ("unsigned.vlt", numbers("unsigned integer types", INTS[5:], False)),
    ("floats.vlt", numbers("float types and `string`", FLOATS, True)),
    ("index.vlt", index()),
]
for name, text in FILES:
    with open(os.path.join(OUT, name), "w") as f:
        f.write(text)


# tests/golden/lang/operators_numbers.vlt: each number type's operator methods, called through
# generic code, give what the built-in operator gives on edge values (overflow included).
EDGES = {
    "i8": ["-128", "-1", "0", "1", "7", "127"],
    "i16": ["-32768", "-1", "0", "3", "32767"],
    "i32": ["-2147483648", "-1", "0", "1", "13", "2147483647"],
    "i64": ["-9223372036854775808", "-1", "0", "5", "9223372036854775807"],
    "isize": ["-9223372036854775808", "-1", "0", "5", "9223372036854775807"],
    "u8": ["0", "1", "128", "255"],
    "u16": ["0", "1", "40000", "65535"],
    "u32": ["0", "1", "3000000000", "4294967295"],
    "u64": ["0", "1", "18446744073709551615"],
    "usize": ["0", "1", "18446744073709551615"],
    "f32": ["-0", "0.5", "-3.25", "1e30", "Infinity as f32", "NaN as f32"],
    "f64": ["-0", "0.5", "-3.25", "1e300", "Infinity", "NaN", "2147483648", "-7"],
}


def golden():
    ifaces = [b[0] for b in BINARY] + ["Neg", "BitNot"]
    out = [
        "// Generated by scripts/gen-ops.py: change the script, not this file.",
        "//",
        "// The operator methods `velt/ops` gives the number types mean exactly what the built-in",
        "// operators mean (#2050): called through generic code, each gives the operator's result",
        "// on edge values, overflow and NaN included. Results are compared as text, where -0 reads",
        "// as 0 and NaN as NaN.",
        "",
        f'import type {{ {", ".join(ifaces)} }} from "velt/ops";',
        "",
    ]
    for iface, key, op, _ in BINARY:
        out += [
            f"function {key}<T extends {iface}<T>>(a: T, b: T): T {{",
            f"  return a {op} b;",
            "}",
        ]
    out += [
        "function neg<T extends Neg<T>>(a: T): T {",
        "  return -a;",
        "}",
        "function bitNot<T extends BitNot<T>>(a: T): T {",
        "  return ~a;",
        "}",
        "",
        "let checks = 0;",
        "let wrong = 0;",
        "function same(a: string, b: string, what: string) {",
        "  checks++;",
        "  if (a != b) {",
        "    wrong++;",
        "    console.log(`${what}: ${a} != ${b}`);",
        "  }",
        "}",
        "",
    ]
    for t, vals in EDGES.items():
        is_float = t.startswith("f")
        bitwise = not is_float or t == "f64"
        signed = not t.startswith("u")
        out.append(f"function check_{t}() {{")
        out.append(f"  const xs: {t}[] = [{', '.join(vals)}];")
        out.append("  for (const a of xs) {")
        if signed:
            out.append(f'    same(`${{neg(a)}}`, `${{-a}}`, `{t} -${{a}}`);')
        if bitwise:
            out.append(f'    same(`${{bitNot(a)}}`, `${{~a}}`, `{t} ~${{a}}`);')
        out.append("    for (const b of xs) {")
        for _, key, op, _ in BINARY:
            if op in ["&", "|", "^", "<<", ">>", ">>>"] and not bitwise:
                continue
            guard = ""
            if op in ["/", "%"] and not is_float:
                guard = "b != 0 && "
            if op == "**" and not is_float:
                guard = "b < 4 && a < 64 && "
                if signed:
                    guard = "b >= 0 && b < 4 && a < 64 && a > -64 && "
            if op in ["<<", ">>", ">>>"] and not is_float:
                guard = "b < 8 && " if not signed else "b >= 0 && b < 8 && "
            line = f'same(`${{{key}(a, b)}}`, `${{a {op} b}}`, `{t} ${{a}} {op} ${{b}}`);'
            if guard:
                out.append(f"      if ({guard[:-4]}) {{")
                out.append(f"        {line}")
                out.append("      }")
            else:
                out.append(f"      {line}")
        out.append("    }")
        out.append("  }")
        out.append("}")
        out.append(f"check_{t}();")
        out.append("")
    out.append("console.log(`${checks} checks, ${wrong} wrong`);")
    out.append("")
    return "\n".join(out)


GOLDEN = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "golden", "lang")
with open(os.path.join(GOLDEN, "operators_numbers.vlt"), "w") as f:
    f.write(golden())
