#!/usr/bin/env node
// Generates std/lang/hooks/inspect_layout_width_table.velt: the display width of every code point,
// as Node's `util.inspect` counts it when it aligns an array's entries in columns
// (`getStringWidth` in lib/internal/util/inspect.js, which calls ICU's East Asian width, general
// category and emoji properties in src/node_i18n.cc). The widths are read from Node itself, one
// code point at a time, so the table is Node's by construction.
//
//   node --expose-internals scripts/gen-inspect-width.js
//
// It runs only on the Node, ICU and Unicode versions below, so a later run on another Node can't
// change the table without this file saying so: update the versions, run it, and check the
// `inspect_layout` goldens and corpus against that Node.

"use strict";
const fs = require("fs");
const path = require("path");

const NODE_MAJOR = "22";
const ICU = "78.3";
const UNICODE = "17.0";

const v = process.versions;
if (v.node.split(".")[0] !== NODE_MAJOR || v.icu !== ICU || v.unicode !== UNICODE) {
  throw new Error(
    `the table is Node ${NODE_MAJOR}'s (ICU ${ICU}, Unicode ${UNICODE}); ` +
      `this is Node ${v.node} (ICU ${v.icu}, Unicode ${v.unicode})`,
  );
}

let getStringWidth;
try {
  ({ getStringWidth } = require("internal/util/inspect"));
} catch {
  throw new Error("run it with `node --expose-internals`");
}

// Runs of code points with the same width, surrogates left out (they never reach the table: the
// layout reads UTF-8, where a lone surrogate is three bytes Node shows as one unit of width 1).
const runs = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  // `removeControlChars` false: `groupArrayElements` passes `ctx.colors`, false for console.log.
  const w = getStringWidth(String.fromCodePoint(cp), false);
  // Node normalizes to NFC before it measures, which splits nine musical symbols
  // (U+1D160..U+1D164, U+1D1BD..U+1D1C0) into three code points: 3 is the widest one gets.
  if (w < 0 || w > 3) throw new Error(`U+${cp.toString(16)}: width ${w}`);
  const last = runs[runs.length - 1];
  if (last && last.width === w) continue;
  runs.push({ start: cp, width: w });
}

const lines = [];
lines.push(
  "// velt/lang/hooks (internal): the display width of each code point in an array's columns",
  "// (inspect_layout_width.velt), generated by scripts/gen-inspect-width.js: do not edit.",
  "//",
  `// From Node ${NODE_MAJOR}'s \`getStringWidth\` (ICU ${ICU}, Unicode ${UNICODE}), read one code point at a`,
  "// time: 0 for control characters, combining marks and format characters, 2 for East Asian wide",
  "// and full-width characters and emoji presentation (the skin tones U+1F3FB..U+1F3FF included),",
  "// 3 for the nine musical symbols NFC splits into three code points, 1 for the rest. One word per",
  "// run of code points with the same width, in order: the run's first code point shifted left by 2,",
  "// or'ed with its width. A run lasts until the next word's code point.",
  "//",
  "// Derived from Unicode Character Database data, © Unicode, Inc., Unicode License v3",
  "// (https://www.unicode.org/license.txt).",
  "",
  `/** How many runs \`WIDTH_RUNS\` holds. */`,
  `export const WIDTH_RUN_COUNT: u64 = ${runs.length};`,
  "",
  "/** The runs: first code point << 2 | width. */",
  "export const WIDTH_RUNS: u32[] = [",
);
for (const r of runs) {
  lines.push(`  0x${((r.start << 2) | r.width).toString(16).padStart(8, "0")},`);
}
lines.push("];", "");

const out = path.join(__dirname, "..", "std", "lang", "hooks", "inspect_layout_width_table.velt");
fs.writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${runs.length} runs`);
