#!/usr/bin/env python3
"""Writes std/lang/number/pow10.velt: the powers of ten that std/lang/number/shortest.velt
(shortest digits of a double, Schubfach) multiplies by.

For k from -324 to 292: 10^-k = beta * 2^r with 2^125 <= beta < 2^126, and g = floor(beta) + 1,
split into its high 63 bits g1 and low 63 bits g0 (R. Giulietti, "The Schubfach way to render
doubles", 2020; the JDK's MathUtils holds the same table).

A table of all 617 costs every program that prints a float the check of 1,234 literals, so the
file holds every STEP-th, below which a multiplication by a power of five gives the others: see
`rebuild`, which is the code of `pow10` in shortest.velt, and which this script checks against every
exact value. What the multiplication loses is at most ADJUST_MAX, kept in two bits per k.
"""
from fractions import Fraction
import sys

K_MIN, K_MAX = -324, 292
STEP = 27
ADJUST_MAX = 3
MASK63 = (1 << 63) - 1
MASK64 = (1 << 64) - 1
PER_WORD = 32


def flog2pow10(e):
    return (e * 913124641741) >> 38


def exact(k):
    r = flog2pow10(-k) - 125
    beta = Fraction(10) ** (-k) / Fraction(2) ** r
    assert (1 << 125) <= beta < (1 << 126), k
    return beta.numerator // beta.denominator + 1


def coarse(n):
    """The g of the n-th kept k, less one so that a product is never above the exact value."""
    return exact(K_MIN + n * STEP) - 1


def rebuild(k, adjust):
    """`pow10` of shortest.velt, on 64-bit words: g of k as (g1, g0)."""
    at = k - K_MIN
    n = (at + STEP - 1) // STEP
    j = n * STEP - at
    c = coarse(n)
    c1, c0 = c >> 63, c & MASK63
    m = 5**j
    high0, low0 = (c0 * m) >> 64, (c0 * m) & MASK64
    high1, low1 = (c1 * m) >> 64, (c1 * m) & MASK64
    # The product in 63-bit limbs p2, p1, p0.
    t = ((low0 >> 63) | (high0 << 1)) + (low1 & MASK63)
    assert t <= MASK64, k
    p0 = low0 & MASK63
    p1 = t & MASK63
    p2 = (t >> 63) + (low1 >> 63) + (high1 << 1)
    assert p2 <= MASK64, k
    # 10^-k = 10^-b * 5^j * 2^j, for the kept b = k + j.
    sh = flog2pow10(-k) - flog2pow10(-(k + j)) - j
    assert 0 <= sh < 63, k
    g1 = ((p1 >> sh) | (p2 << (63 - sh))) & MASK63
    g0 = (((p0 >> sh) | (p1 << (63 - sh))) & MASK63) + adjust
    return g1 + (g0 >> 63), g0 & MASK63


def tables():
    adjusts = []
    for k in range(K_MIN, K_MAX + 1):
        want = exact(k)
        want = (want >> 63, want & MASK63)
        adjust = next((a for a in range(ADJUST_MAX + 1) if rebuild(k, a) == want), None)
        assert adjust is not None, k
        adjusts.append(adjust)
    words = [0] * ((len(adjusts) + PER_WORD - 1) // PER_WORD)
    for i, a in enumerate(adjusts):
        words[i // PER_WORD] |= a << (2 * (i % PER_WORD))
    kept = []
    for n in range((K_MAX - K_MIN + STEP - 1) // STEP + 1):
        c = coarse(n)
        kept += [c >> 63, c & MASK63]
    return kept, [5**j for j in range(STEP)], words


def table(lines, name, values):
    lines.append(f"export const {name}: u64[] = [")
    lines.extend(f"  0x{v:016x}," for v in values)
    lines.extend(["];", ""])


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "std/lang/number/pow10.velt"
    kept, fives, words = tables()
    lines = [
        "// velt/lang/number (internal): powers of ten for the shortest digits of a double,",
        "// generated by scripts/gen-pow10-table.py: do not edit.",
        "//",
        f"// For k from {K_MIN} to {K_MAX}, 10^-k as g = floor(beta) + 1, where 10^-k = beta * 2^r and",
        "// 2^125 <= beta < 2^126: its high 63 bits, then its low 63 bits. `pow10` in",
        f"// std/lang/number/shortest.velt rebuilds each from `KEPT` (every {STEP}th k, less 1), `FIVES`",
        f"// and `ADJUST` (two bits per k, {PER_WORD} per word); the script checks every one.",
        "",
        f"export const G_K_MIN: i64 = {K_MIN};",
        f"export const G_STEP: i64 = {STEP};",
        "",
    ]
    table(lines, "KEPT", kept)
    table(lines, "FIVES", fives)
    table(lines, "ADJUST", words)
    with open(out, "w") as f:
        f.write("\n".join(lines).rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
