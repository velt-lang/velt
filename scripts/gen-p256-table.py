#!/usr/bin/env python3
"""Writes std/crypto/p256_table.vlt: the multiples of the P-256 base point that key generation
adds (std/crypto/p256.vlt, `p256PublicKey`), affine and in the field's Montgomery domain.
Window i (0..64) holds j * 16^i * G for j = 1..8, each as x then y, four little-endian 64-bit
limbs each: entry (i, j) starts at limb 64 i + 8 (j - 1).

    python3 scripts/gen-p256-table.py > std/crypto/p256_table.vlt
"""

P = 2**256 - 2**224 + 2**192 + 2**96 - 1
A = P - 3
G = (
    0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
    0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5,
)
R = 2**256


def add(p, q):
    if p is None:
        return q
    if q is None:
        return p
    if p[0] == q[0] and (p[1] + q[1]) % P == 0:
        return None
    if p == q:
        lam = (3 * p[0] * p[0] + A) * pow(2 * p[1], -1, P) % P
    else:
        lam = (q[1] - p[1]) * pow(q[0] - p[0], -1, P) % P
    x = (lam * lam - p[0] - q[0]) % P
    return (x, (lam * (p[0] - x) - p[1]) % P)


limbs = []
base = G
for i in range(65):
    acc = None
    for j in range(1, 9):
        acc = add(acc, base)
        for c in acc:
            m = c * R % P
            limbs.extend((m >> (64 * k)) & (2**64 - 1) for k in range(4))
    for _ in range(4):
        base = add(base, base)

print(
    "// velt/crypto (internal): the P-256 base point's multiples j * 16^i * G (j = 1..8, i = 0..64)\n"
    "// that key generation adds, affine, x then y, in the field's Montgomery domain: entry (i, j)\n"
    "// starts at limb 64 i + 8 (j - 1). A module constant that is an array of number literals, so\n"
    "// it is stored once in the program (33 KiB).\n"
    "// Generated by scripts/gen-p256-table.py; edit that and run it again.\n"
    "\n"
    "/** The base point table: 65 windows of 8 affine points. */\n"
    "export const P256_BASE: u64[] = [\n"
    + "".join(f"  0x{x:016x},\n" for x in limbs)
    + "];"
)
