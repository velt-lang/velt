#!/usr/bin/env python3
# Generates the operators of `velt/simd` (std/simd/ops_*.vlt): the operator methods (design
# docs/internals/design/operators.md) of the ten vector types and four mask types, each the
# lane operation its named method is (`a + b` is `a.add(b)`), calling the same `velt_simd_*`
# operation directly so a debug build inlines it too. A scalar operand (`v * 2`) is splatted by
# the compiler (velt_sema `operator_simd.rs`). To change them, change this script and run it
# from the repository root, then `velt fmt` the files:
#
#   python3 scripts/gen-simd-ops.py && velt fmt std/simd/ops_*.vlt
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "std", "simd")
TYPES = [("i8", 16), ("u8", 16), ("i16", 8), ("u16", 8), ("i32", 4), ("u32", 4), ("i64", 2),
         ("u64", 2), ("f32", 4), ("f64", 2)]


def name(l, n):
    return f"{l}x{n}"


def bits(l):
    return int(l[1:])


def isf(l):
    return l[0] == "f"


def signed(l):
    return l[0] == "i"


HEAD = """// velt/simd (internal): the operators of the {what}. Programs import the types from
// `velt/simd`.
//
// `a + b` on vectors is the lane operation `a.add(b)` is, and so on (design operators.md):
// each operator method below calls the same operation, which the compiler emits inline. A
// scalar operand is splatted (`v * 2` is `v * f32x4.splat(2)`; a variable must have the lane
// type). Comparisons stay methods (`a.lt(b)`): they give a mask, and `==` gives a `bool`.
//
// Generated by scripts/gen-simd-ops.py: change the script, not this file.
"""


def vector(l, n):
    T = name(l, n)
    P = f"velt_simd_{T}_"
    f = isf(l)
    decls, ms = [], []

    def decl(op, params, ret):
        decls.append(f"declare function {P}{op}({params}): {ret};")

    def binary(key, op, sym, doc):
        decl(op, f"a: {T}, b: {T}", T)
        ms.append(f"""  /** `this {sym} other`: {doc} */
  [Symbol.{key}](other: {T}): {T} {{
    return {P}{op}(this, other);
  }}
""")

    w = "" if f else ", wrapping on overflow"
    binary("add", "add", "+", f"the lane-wise sum{w}.")
    binary("sub", "sub", "-", f"the lane-wise difference{w}.")
    if f or bits(l) != 8:
        binary("mul", "mul", "*", f"the lane-wise product{w}.")
    if f:
        binary("div", "div", "/", "the lane-wise quotient.")
    if not f:
        binary("bitAnd", "and", "&", "bitwise AND.")
        binary("bitOr", "or", "|", "bitwise OR.")
        binary("bitXor", "xor", "^", "bitwise XOR.")
    if f or signed(l):
        decl("neg", f"v: {T}", T)
        ms.append(f"""  /** `-this`: each lane negated{'' if f else ' (wrapping)'}. */
  [Symbol.neg](): {T} {{
    return {P}neg(this);
  }}
""")
    if not f:
        decl("not", f"v: {T}", T)
        ms.append(f"""  /** `~this`: every bit flipped. */
  [Symbol.bitNot](): {T} {{
    return {P}not(this);
  }}
""")
        b = bits(l)
        decl("shl", f"v: {T}, count: u32", T)
        decl("shr", f"v: {T}, count: u32", T)
        ms.append(f"""  /** `this << count`: each lane shifted left by `count` bits (taken modulo {b}). */
  [Symbol.shl](count: u32): {T} {{
    return {P}shl(this, count);
  }}

  /**
   * `this >> count`: each lane shifted right by `count` bits (taken modulo {b}),
   * {'keeping the sign' if signed(l) else 'filling with zeros'}.
   */
  [Symbol.shr](count: u32): {T} {{
    return {P}shr(this, count);
  }}
""")
        if signed(l):
            U = name("u" + l[1:], n)
            UP = f"velt_simd_{U}_"
            decl(f"as_{U}", f"v: {T}", U)
            decls.append(f"declare function {UP}shr(v: {U}, count: u32): {U};")
            decls.append(f"declare function {UP}as_{T}(v: {U}): {T};")
            ms.append(f"""  /** `this >>> count`: each lane shifted right by `count` bits (taken modulo {b}), filling with zeros. */
  [Symbol.ushr](count: u32): {T} {{
    return {UP}as_{T}({UP}shr({P}as_{U}(this), count));
  }}
""")
        else:
            ms.append(f"""  /** `this >>> count`: each lane shifted right by `count` bits (taken modulo {b}), filling with zeros. */
  [Symbol.ushr](count: u32): {T} {{
    return {P}shr(this, count);
  }}
""")
    decl("lane", f"v: {T}, index: u64", l)
    ms.append(f"""  /** `this[index]`: lane `index` (0 to {n - 1}; panics with a RangeError otherwise). */
  [Symbol.index](index: usize): {l} {{
    if (index >= {n}) {{
      panic("RangeError: {T}[index]: index is out of range");
    }}
    return {P}lane(this, index as u64);
  }}
""")
    return decls, f"extend {T} {{\n" + "\n".join(ms) + "}\n"


def mask(b, n):
    M = f"mask{b}x{n}"
    P = f"velt_simd_{M}_"
    out = [
        f"declare function {P}and(a: {M}, b: {M}): {M};",
        f"declare function {P}or(a: {M}, b: {M}): {M};",
        f"declare function {P}xor(a: {M}, b: {M}): {M};",
        f"declare function {P}not(m: {M}): {M};",
        "",
        f"extend {M} {{",
    ]
    for key, op, sym, doc in [("bitAnd", "and", "&", "the lanes set in both masks."),
                              ("bitOr", "or", "|", "the lanes set in either mask."),
                              ("bitXor", "xor", "^", "the lanes set in exactly one of the masks.")]:
        out += [f"  /** `this {sym} other`: {doc} */",
                f"  [Symbol.{key}](other: {M}): {M} {{",
                f"    return {P}{op}(this, other);",
                "  }",
                ""]
    out += ["  /** `~this`: the lanes that are not set. */",
            f"  [Symbol.bitNot](): {M} {{",
            f"    return {P}not(this);",
            "  }",
            "}",
            ""]
    return "\n".join(out)


FILES = {
    "ops_bytes": ("vectors of 8- and 16-bit lanes", [t for t in TYPES if bits(t[0]) <= 16]),
    "ops_words": ("vectors of 32- and 64-bit integer lanes",
                  [t for t in TYPES if bits(t[0]) >= 32 and not isf(t[0])]),
    "ops_floats": ("vectors of float lanes", [t for t in TYPES if isf(t[0])]),
}
for part, (what, ts) in FILES.items():
    decls, bodies = [], []
    for l, n in ts:
        d, b = vector(l, n)
        decls += [x for x in d if x not in decls]
        bodies.append(b)
    text = HEAD.format(what=what) + "\n" + "\n".join(decls) + "\n\n" + "\n".join(bodies)
    open(os.path.join(OUT, f"{part}.vlt"), "w", encoding="utf-8", newline="\n").write(text)
text = HEAD.format(what="masks") + "\n" + "\n".join(mask(b, 128 // b) for b in (8, 16, 32, 64))
open(os.path.join(OUT, "ops_masks.vlt"), "w", encoding="utf-8", newline="\n").write(text)
