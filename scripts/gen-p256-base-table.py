#!/usr/bin/env python3
"""Writes std/crypto/p256_base_table.velt: multiples of the P-256 base point G for its fixed-base
multiplication (std/crypto/p256.velt `baseMultiply`, #2955). Window i (0..63, the scalar's 4-bit
digits from the least significant) holds j * 16^i * G for j = 1..15, affine, each coordinate in
the Montgomery domain (times 2^256 mod p) as four little-endian 64-bit limbs: x then y, 8 limbs a
point, entry (i, j) at (15 * i + j - 1) * 8.

    python3 scripts/gen-p256-base-table.py > std/crypto/p256_base_table.velt
"""

P = 2**256 - 2**224 + 2**192 + 2**96 - 1
A = P - 3
GX = 0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296
GY = 0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5
WINDOWS = 64
DIGITS = 15


def inv(x):
    return pow(x, P - 2, P)


def add(p1, p2):
    """Affine addition (None is the identity)."""
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    (x1, y1), (x2, y2) = p1, p2
    if x1 == x2:
        if (y1 + y2) % P == 0:
            return None
        lam = (3 * x1 * x1 + A) * inv(2 * y1) % P
    else:
        lam = (y2 - y1) * inv(x2 - x1) % P
    x3 = (lam * lam - x1 - x2) % P
    return (x3, (lam * (x1 - x3) - y1) % P)


def limbs(v):
    m = v * 2**256 % P
    return [(m >> (64 * k)) & (2**64 - 1) for k in range(4)]


def main():
    words = []
    base = (GX, GY)
    for _ in range(WINDOWS):
        point = None
        for _ in range(DIGITS):
            point = add(point, base)
            # `baseMultiply` reads an x of zero as "no entry selected" (a zero digit).
            assert limbs(point[0]) != [0, 0, 0, 0]
            words += limbs(point[0]) + limbs(point[1])
        # The next window's base: 16 times this one's.
        for _ in range(4):
            base = add(base, base)
    print(
        "// velt/crypto (internal): multiples of the P-256 base point G for its fixed-base\n"
        "// multiplication (std/crypto/p256.velt `baseMultiply`): window i holds j * 16^i * G for\n"
        "// j = 1..15, affine, x then y in the Montgomery domain as little-endian limbs, entry (i, j)\n"
        "// at (15 * i + j - 1) * 8. A module constant that is an array of number literals, so it is\n"
        "// stored once in the program and read where it is.\n"
        "// Generated by scripts/gen-p256-base-table.py; edit that and run it again.\n"
        "\n"
        "/** j * 16^i * G for the 64 windows i and the digits j = 1..15 (see the file's comment). */\n"
        "export const P256_BASE: u64[] = ["
    )
    for w in words:
        print(f"  0x{w:016x},")
    print("];")


main()
