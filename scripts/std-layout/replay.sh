#!/usr/bin/env bash
# Replays the std move (docs/internals/design/std-layout.md) onto a newer main: the commits
# before the generated one are cherry-picked, the generated one is made again by running
# scripts/std-layout/main.vlt (so code merged to main meanwhile is moved and rewritten too),
# and the hand-written commits after it are cherry-picked on top.
#
#   scripts/std-layout/replay.sh [base]        # base: origin/main by default
#
# Run it from the std-layout branch with a built `velt` (target/debug/velt, or $VELT): the
# script runs with that velt and a copy of the branch's std, both from after the move. The old
# branch head is kept as std-layout-before-replay. If a std file merged meanwhile has no rule,
# the script stops and names it: add the rule to layout.vlt in the "scripts:" commit (amend it),
# and run this again. If a cherry-pick conflicts, resolve it and `git cherry-pick --continue`.
set -euo pipefail

base="${1:-origin/main}"
root="$(git rev-parse --show-toplevel)"
cd "$root"
velt="${VELT:-$root/target/debug/velt}"
generated_subject='std: the move to velt/<area> modules (generated by scripts/std-layout)'

if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
  echo "replay: the work tree has changes; commit them first" >&2
  exit 1
fi
if [ ! -x "$velt" ]; then
  echo "replay: no velt at $velt (cargo build -p veltc --bin velt, or set VELT)" >&2
  exit 1
fi
[ "$base" = "origin/main" ] && git fetch -q origin main

branch="$(git branch --show-current)"
head="$(git rev-parse HEAD)"
generated="$(git log --format=%H --fixed-strings --grep="$generated_subject" -1)"
if [ -z "$generated" ]; then
  echo "replay: no commit '$generated_subject' on this branch" >&2
  exit 1
fi
old_base="$(git merge-base "$generated" "$base")"
pre=($(git rev-list --reverse "$old_base..$generated~1"))
post=($(git rev-list --reverse "$generated..$head"))
message="$(git log -1 --format=%B "$generated")"

# The script runs with a std from after the move; checking out the base replaces std/.
std_copy="$(mktemp -d)"
trap 'rm -rf "$std_copy"' EXIT
cp -R std "$std_copy/std"

git branch -f std-layout-before-replay "$head"
echo "replay: ${#pre[@]} commits, then the generated one, then ${#post[@]} commits onto $base"
git checkout -q -B "$branch" "$base"
[ ${#pre[@]} -eq 0 ] || git cherry-pick "${pre[@]}"
VELT_STD="$std_copy/std" "$velt" run scripts/std-layout/main.vlt
"$velt" fmt std examples > /dev/null
git add -A
git commit -q -m "$message"
[ ${#post[@]} -eq 0 ] || git cherry-pick "${post[@]}"
echo "replay: done; build and test it (scripts/check.sh). The old head is std-layout-before-replay."
