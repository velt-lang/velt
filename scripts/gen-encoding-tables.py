#!/usr/bin/env python3
"""Writes std/encoding/tables.vlt: the lookup tables of velt/encoding's Base64 (RFC 4648 §4, and
§5 for the URL-safe alphabet) and hex codecs.

    python3 scripts/gen-encoding-tables.py > std/encoding/tables.vlt
"""

STD = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
URL = STD[:62] + "-_"
INVALID = 255


def values(alphabet):
    v = [-1] * 256
    for i, c in enumerate(alphabet):
        v[ord(c)] = i
    return v


def hex_values():
    v = [INVALID] * 256
    for i, c in enumerate("0123456789abcdef"):
        v[ord(c)] = i
        v[ord(c.upper())] = i
    return v


def table(doc, name, ty, xs):
    out = doc + f"export const {name}: {ty}[] = [\n"
    out += "".join(f"  {x},\n" for x in xs)
    return out + "];\n"


print(
    "// velt/encoding (internal): the lookup tables of std/encoding. Module constants that\n"
    "// are arrays of number literals, so each is stored once in the program and read where it is.\n"
    "// Generated by scripts/gen-encoding-tables.py; edit that and run it again.\n"
    "\n"
    "// Base64 digits by value (RFC 4648 §4, and §5 for the URL-safe alphabet), and the value of every\n"
    "// byte as a digit: -1 for the others, signed so that one sign test finds a byte that is not a\n"
    "// digit among four.\n"
    "\n"
    + table("/** Standard Base64 digits by value. */\n", "STD_DIGITS", "u8", [ord(c) for c in STD])
    + table("/** URL-safe Base64 digits by value. */\n", "URL_DIGITS", "u8", [ord(c) for c in URL])
    + table(
        "/** The value of every byte as a standard Base64 digit, -1 for the others. */\n",
        "STD_VALUES",
        "i8",
        values(STD),
    )
    + table(
        "/** The value of every byte as a URL-safe Base64 digit, -1 for the others. */\n",
        "URL_VALUES",
        "i8",
        values(URL),
    )
    + table(
        "\n/**\n * The value of every byte as a hex digit of either case, 255 (std/encoding's `INVALID`) for the\n * others.\n */\n",
        "HEX_VALUES",
        "u8",
        hex_values(),
    ),
    end="",
)
