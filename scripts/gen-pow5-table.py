#!/usr/bin/env python3
"""Writes std/lang/number/pow5.vlt: the 128-bit powers of five of the Eisel-Lemire float parser
(std/lang/number/eisel_lemire.vlt), for decimal exponents -342 to 308, as fast_float and Rust's core::num
::dec2flt compute them: 5^q with its top bit at bit 127, truncated (q >= 0); for q < 0, the
reciprocal 2^b / 5^-q rounded up (b = z + 127 for q >= -27, else
2z + 128 and truncated to 128 bits; 2^z is the first power of two above 5^-q).

    python3 scripts/gen-pow5-table.py > std/lang/number/pow5.vlt
"""

SMALLEST, LARGEST = -342, 308


def entry(q):
    if q >= 0:
        p = 5 ** q
        while p < (1 << 127):
            p *= 2
        while p >= (1 << 128):
            p //= 2
        return p
    p = 5 ** -q
    z = p.bit_length()
    if q >= -27:
        # 5^-q fits in 64 bits: the reciprocal fits in 128 without truncation.
        return (1 << (z + 127)) // p + 1
    b = 2 * z + 2 * 64
    c = (1 << b) // p + 1
    while c >= (1 << 128):
        c //= 2
    return c


print("// velt/lang/number/pow5 (std-internal), generated by scripts/gen-pow5-table.py: do not edit.")
print("//")
print(f"// 5^q for q from {SMALLEST} to {LARGEST}, 128 bits each (high word, then low), normalized and")
print("// truncated as fast_float and Rust's core::num::dec2flt make them (std/lang/number/eisel_lemire.vlt).")
print("")
print(f"export const POW5_SMALLEST: i64 = {SMALLEST};")
print(f"export const POW5_LARGEST: i64 = {LARGEST};")
print("")
print("export const POW5: u64[] = [")
for q in range(SMALLEST, LARGEST + 1):
    e = entry(q)
    # One word per line, as `velt fmt` lays out an array literal that does not fit on one line.
    print(f"  0x{e >> 64:016x},")
    print(f"  0x{e & ((1 << 64) - 1):016x},")
print("];")
