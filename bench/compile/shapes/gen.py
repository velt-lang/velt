#!/usr/bin/env python3
"""Writes a Velt program whose `any` arrays are converted to N element types (array views,
#1485), for generic instances shared by shape (docs/internals/design/shape-sharing.md).

    gen.py [object types = 40] [out file = shapes.velt] [sites = 0]

The object types come in three layouts (two numbers; a number and a string; two strings and
a number), with field names of their own, so each is a type of its own; a union and `string`
are added. Without sharing, each element type gets its own instance of each array-view helper;
with it, each shape does. The program prints a checksum, the same either way.

With `sites` > 0 it also reads one view at that many sites (one function each), the case where
sharing gains nothing and what it costs per call of a shared helper shows.
"""
import sys

n = int(sys.argv[1]) if len(sys.argv) > 1 else 40
out = sys.argv[2] if len(sys.argv) > 2 else "shapes.velt"
sites = int(sys.argv[3]) if len(sys.argv) > 3 else 0

layouts = [
    lambda i: (f"{{ x{i}: number; y{i}: number }}", f"{{ x{i}: k, y{i}: k * 2 }}", f"o.x{i} + o.y{i}"),
    lambda i: (f"{{ x{i}: number; s{i}: string }}", f"{{ x{i}: k, s{i}: \"s\" + k }}", f"o.x{i} + o.s{i}.length"),
    lambda i: (f"{{ s{i}: string; t{i}: string; x{i}: number }}", f"{{ s{i}: \"a\", t{i}: \"bc\", x{i}: k }}", f"o.s{i}.length + o.t{i}.length + o.x{i}"),
]

lines = ["// Generated by bench/compile/shapes/gen.py: array views of many element types.", ""]
for i in range(n):
    ty, _, _ = layouts[i % 3](i)
    lines.append(f"type O{i} = {ty};")
lines.append("type U = O0 | string | number;")
lines.append("")
for i in range(n):
    _, lit, use = layouts[i % 3](i)
    lines += [
        f"function make{i}(m: number): any {{",
        "  const xs: any[] = [];",
        "  for (let k = 0; k < m; k++) {",
        f"    const o: O{i} = {lit};",
        "    xs.push(o);",
        "  }",
        "  return xs;",
        "}",
        "",
        f"function sum{i}(m: number): number {{",
        f"  const view = make{i}(m) as O{i}[];",
        "  let t = 0;",
        "  for (const o of view) {",
        f"    t += {use};",
        "  }",
        "  view.push(view[0]);",
        "  return t + view.length;",
        "}",
        "",
    ]
lines += [
    "function sumU(m: number): number {",
    "  const xs: any[] = [];",
    "  for (let k = 0; k < m; k++) {",
    "    xs.push(k % 2 === 0 ? \"u\" : k);",
    "  }",
    "  const view = (xs as any) as U[];",
    "  let t = 0;",
    "  for (const u of view) {",
    "    t += typeof u === \"string\" ? u.length : typeof u === \"number\" ? u : 0;",
    "  }",
    "  return t;",
    "}",
    "",
    "function sumS(m: number): number {",
    "  const xs: any[] = [];",
    "  for (let k = 0; k < m; k++) {",
    "    xs.push(\"s\" + k);",
    "  }",
    "  const view = (xs as any) as string[];",
    "  let t = 0;",
    "  for (const s of view) {",
    "    t += s.length;",
    "  }",
    "  return t;",
    "}",
    "",
    "let total = sumU(10) + sumS(10);",
]
for i in range(n):
    lines.append(f"total += sum{i}(5);")
if sites > 0:
    view = "const sv = make0(3) as O0[];"
    lines.insert(lines.index("let total = sumU(10) + sumS(10);"), view)
    for k in range(sites):
        lines.insert(lines.index(view), f"function site{k}(v: O0[]): number {{\n  return v[{k % 3}].x0;\n}}\n")
    for k in range(sites):
        lines.append(f"total += site{k}(sv);")
lines.append("console.log(total);")
open(out, "w").write("\n".join(lines) + "\n")
