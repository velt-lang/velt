use rng::Rng;
use scope::{Scope, Ty};

/// A generated helper function the program may call.
#[derive(Clone, Debug)]
pub struct FnSig {
    name: String,
    params: Vec<(Ty, String)>,
    ret: Option<Ty>,
    throws: bool,
    /// The last parameter has a default value and may be omitted.
    default_last: bool,
    /// `async function`: called only as `await h(...)` directly in an async body.
    is_async: bool,
    /// Its body neither prints nor awaits, so concurrent runs (`Promise.all`) can't interleave
    /// observably (JS starts promises eagerly, Velt lazily on a multi-threaded runtime).
    quiet: bool,
}

/// The generated class hierarchy: `K0` (implements `Calc`) and optionally `K1 extends K0`.
/// Every class has int field `a`, string field `s` (plus `b: i64` in `K1`), `calc(k)`, `bump(k)`
/// and getter `tag`.
#[derive(Clone, Debug)]
pub struct ClassInfo {
    fields: Vec<(String, Ty)>,
}

/// Generation settings.
#[derive(Clone, Copy, Debug, Default)]
pub struct Options {
    /// Full-range integers (wrapping), casts and unguarded division: programs outside the
    /// JS-compatible subset, checked against the debug build instead of Node.
    pub wild: bool,
    /// Programs over the std modules instead (see `stdlib`).
    pub std: bool,
}

/// Generator state: randomness, scope, declared helpers/classes and the output buffer.
pub struct Gen {
    rng: Rng,
    scope: Scope,
    funcs: Vec<FnSig>,
    classes: Vec<ClassInfo>,
    out: String,
    indent: usize,
    /// Statements left to emit in the current function (bounds program size).
    budget: usize,
    /// Nesting depth of loops (`break`/`continue` allowed when > 0).
    loops: usize,
    /// Inside a `try` body: calls to throwing helpers are allowed.
    in_try: bool,
    /// Nesting depth of blocks (bounds control-flow depth).
    depth: usize,
    /// Labels of the enclosing loops (`None` for unlabeled ones), innermost last.
    labels: Vec<Option<String>>,
    /// The function being generated: `None` while in `main`, else the helper's return type
    /// (`Some(None)` for void helpers). Drives early `return`s (which may cross `finally`).
    ret: Option<Option<Ty>>,
    /// Inside an async function body (awaits allowed outside closures).
    in_async: bool,
    /// See [`Options::wild`].
    wild: bool,
}

/// Generates the program for `seed`.
pub fn program(seed: u64, opts: Options) -> String {
    if opts.std {
        return stdlib::program(seed);
    }
    let mut g = Gen {
        rng: Rng::new(seed),
        scope: Scope::new(),
        funcs: Vec::new(),
        classes: Vec::new(),
        out: format!("// Generated by difftest (seed {seed}).\n"),
        indent: 0,
        budget: 0,
        loops: 0,
        in_try: false,
        depth: 0,
        labels: Vec::new(),
        ret: None,
        in_async: false,
        wild: opts.wild,
    };
    g.classes_decl();
    g.tagged_decl();
    g.library_decl();
    let helpers = g.rng.range(1, 4);
    for _ in 0..helpers {
        g.helper_decl();
    }
    g.main_decl();
    g.out
}

impl Gen {
    /// Emits one line at the current indentation.
    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.out.push_str("  ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    /// Emits `header` (ending in `{`) and opens a block (scope frame + indentation).
    fn open(&mut self, header: &str) {
        self.line(header);
        self.indent += 1;
        self.depth += 1;
        self.scope.push();
    }

    /// Closes the innermost block with `footer` (`}` or `} else {`-style continuations).
    fn close(&mut self, footer: &str) {
        self.scope.pop();
        self.depth -= 1;
        self.indent -= 1;
        self.line(footer);
    }

    /// Declares a fresh binding and returns its name.
    fn bind(&mut self, prefix: &str, ty: Ty, rebind: bool) -> String {
        let name = self.scope.fresh(prefix);
        self.scope.declare(&name, ty, rebind, true);
        name
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn deterministic_and_balanced() {
        for seed in 0..200 {
            let opts = super::Options {
                wild: seed % 2 == 1,
                std: false,
            };
            let p = super::program(seed, opts);
            assert_eq!(
                p,
                super::program(seed, opts),
                "seed {seed} is not reproducible"
            );
            assert_eq!(
                p.matches('{').count(),
                p.matches('}').count(),
                "seed {seed}:\n{p}"
            );
            assert!(p.contains("function main()"));
        }
    }
}
