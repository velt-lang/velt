//! Random program generator for the TypeScript/Velt shared subset.
//!
//! Programs are well typed by construction and avoid every documented semantic difference (see
//! `README.md`): integers stay within ±10007 (every integer operation is reduced `% 10007` in the
//! same statement, so the shrinker can't break the invariant by deleting a line), floats print only
//! through templates/JSON (Velt prints `-0` as `0`), arrays printed by `console.log` are sliced to
//! 6 elements, and non-Copy values in moving positions are always fresh (`${s}`, `xs.slice(0)`,
//! `new K()`), so no program depends on Velt move semantics. Output is one statement per line,
//! blocks closing on their own line, which is what the line-based shrinker relies on.

