//! `--std` programs: random inputs through the deterministic std modules (url, encoding, crypto,
//! csv, regex, datetime), checked against their Node twins in `shims/std` (JS's own `URL`,
//! `RegExp`, `Buffer`, `node:crypto`, `Date`).
//!
//! Every statement is one line wrapped in its own `try` (errors print `error`, or the message
//! where both sides agree on it), so the shrinker can drop statements independently. Inputs
//! stay clear of the known std differences: regex subjects have no `\r` and no supplementary
//! characters (JavaScript's non-`u` `.` and negated classes match half of a pair, #401), patterns
//! can't match the empty string (bugs regex-line-terminators, regex-empty-after-match), `split`
//! only uses patterns without groups (JS yields `undefined` for groups that didn't match).

mod pattern;

use super::rng::Rng;

/// Header: imports and printing helpers shared by all statements.
const PRELUDE: &str = r#"import { URL, URLSearchParams, encodeURIComponent, decodeURIComponent, encodeURI, decodeURI } from "velt:url";
import { base64Encode, base64Decode, base64UrlEncode, base64UrlDecode, base64EncodeString, base64DecodeString, hexEncode, hexDecode, utf8Encode, utf8Decode, utf8DecodeLossy, utf8Valid } from "velt:encoding";
import { sha256, sha1, sha256Hex, sha1Hex, hmacSha256, hmacSha1 } from "velt:crypto";
import { parseCsv, stringifyCsv } from "velt:csv";
import { RegExp, RegExpMatch } from "velt:regex";
import { DateTime, Duration } from "velt:datetime";

function showUrl(u: URL) {
  console.log(u.href, "|", u.protocol, u.username, u.password, u.host, u.hostname, u.port, u.pathname, u.search, u.hash, u.origin);
}

function showMatch(m: RegExpMatch | null): string {
  if (m == null) {
    return "none";
  }
  const groups: string[] = [];
  for (let i: usize = 0; i <= m.captures.length; i++) {
    groups.push(m.group(i) ?? "<null>");
  }
  return `${m.index}..${m.end} ${JSON.stringify(groups)}`;
}

function showDate(d: DateTime) {
  console.log(d.toISOString(), "|", d.toUTCString(), d.toEpochMs(), d.toEpochSeconds(), d.year, d.month, d.day, d.hour, d.minute, d.second, d.millisecond, d.dayOfWeek, d.dayOfYear);
}
"#;

const SCHEMES: [&str; 9] = [
    "http", "https", "HTTP", "ws", "file", "ftp", "mailto", "foo", "wss",
];
const HOSTS: [&str; 14] = [
    "example.com",
    "EXAMPLE.org",
    "127.0.0.1",
    "0x7f.1",
    "[::1]",
    "a.b.c",
    "",
    "ex ample",
    "%41.com",
    "192.168.0.256",
    "xn--nxasmq6b",
    "h",
    "1.2.3",
    "[1:2::3]",
];
const PORTS: [&str; 8] = ["", ":80", ":443", ":8080", ":65535", ":65536", ":0", ":x"];
const SEGMENTS: [&str; 12] = [
    "a", "..", ".", "%2e", "%2E%2e", "a b", "é", "x%zz", "~u", "b;c", "", "A%2fB",
];
const TEXT_CHARS: [&str; 25] = [
    "a",
    "Z",
    "0",
    " ",
    "%",
    "%41",
    "%zz",
    "%E2%9C%93",
    "%C3",
    "+",
    "&",
    "=",
    "?",
    "#",
    "/",
    ":",
    "@",
    "é",
    "✓",
    "\\\"",
    "\\\\",
    "\\n",
    "\\t",
    ",",
    "😀",
];

/// Characters for `host` / `hostname` setter values.
const HOST_CHARS: [&str; 8] = ["a", "Z", "0", ".", "8", "%41", "-", "\\\""];

/// Characters for the other setters: no tab/newline (bug url-setter-tab-newline), no lone `%`
/// (ada's `href` drops it next to an escape).
const SETTER_CHARS: [&str; 16] = [
    "a",
    "Z",
    "0",
    " ",
    "%41",
    "%zz",
    "%E2%9C%93",
    "+",
    "&",
    "=",
    "?",
    "#",
    "/",
    ":",
    "@",
    "é",
];

/// Characters for `username` / `password` setter values.
const USERINFO_CHARS: [&str; 9] = ["a", "Z", "0", " ", "%41", ":", "@", "#", "é"];

/// State of one `--std` program.
pub struct StdGen {
    rng: Rng,
    out: String,
}

/// The `--std` program for `seed`.
pub fn program(seed: u64) -> String {
    let mut g = StdGen {
        rng: Rng::new(seed),
        out: format!(
            "// Generated by difftest --std (seed {seed}).\n{PRELUDE}\nfunction main() {{\n"
        ),
    };
    for _ in 0..g.rng.range(8, 24) {
        let (body, message) = g.statement();
        let catch = match message {
            true => "console.log(\"error\", e.message);",
            false => "console.log(\"error\");",
        };
        g.out
            .push_str(&format!("  try {{ {body} }} catch (e) {{ {catch} }}\n"));
    }
    g.out.push_str("}\n");
    g.out
}

impl StdGen {
    /// One statement and whether its error message is comparable.
    fn statement(&mut self) -> (String, bool) {
        match self.rng.below(12) {
            0..=2 => self.url_stmt(),
            3..=4 => (self.encoding_stmt(), false),
            5 => (self.crypto_stmt(), false),
            6..=7 => (self.csv_stmt(), false),
            8..=9 => (self.regex_stmt(), false),
            _ => (self.datetime_stmt(), false),
        }
    }

    /// A string literal of 0..`max` pieces from `alphabet` (pieces are already escaped).
    fn text(&mut self, alphabet: &[&str], max: i64) -> String {
        let n = self.rng.range(0, max);
        let body: String = (0..n).map(|_| *self.rng.pick(alphabet)).collect();
        format!("\"{body}\"")
    }

    /// A `u8[]` literal, biased towards UTF-8 lead and continuation bytes.
    fn bytes(&mut self, max: i64) -> String {
        let n = self.rng.range(0, max);
        let items: Vec<String> = (0..n)
            .map(|_| {
                let b = match self.rng.below(4) {
                    0 => self.rng.range(0x80, 0xbf),
                    1 => *self.rng.pick(&[0xc3, 0xe2, 0xf0, 0xed, 0xc0, 0xf4, 0xff]),
                    _ => self.rng.range(0, 255),
                };
                b.to_string()
            })
            .collect();
        format!("[{}]", items.join(", "))
    }

    /// A URL-ish string; `hierarchical` forces `scheme://` (a base for relative inputs: Node
    /// 24's ada resolves some relative inputs against opaque-path bases like `mailto:`, which
    /// the WHATWG parser — and std/url — reject). `file:` URLs get no port or credentials (bug
    /// url-file-host-port).
    fn url_text(&mut self, hierarchical: bool) -> String {
        let mut s = String::new();
        let scheme = *self.rng.pick(&SCHEMES);
        s.push_str(scheme);
        let sep = match hierarchical {
            true => "://",
            false => *self.rng.pick(&["://", "://", ":", ":/", ":\\\\\\\\"]),
        };
        s.push_str(sep);
        let file = scheme == "file";
        if !file && self.rng.chance(20) {
            s.push_str(self.rng.pick(&["user@", "u:p@", "a%20b:@", ":pw@"]));
        }
        let host = *self.rng.pick(&HOSTS);
        s.push_str(host);
        if !file {
            s.push_str(self.rng.pick(&PORTS));
        }
        for _ in 0..self.rng.range(0, 3) {
            s.push('/');
            // With no host, a special URL takes the first segment as its host, and std/url has
            // no IDNA (documented): keep such hosts ASCII.
            let seg = match *self.rng.pick(&SEGMENTS) {
                "é" if host.is_empty() => "e",
                seg => seg,
            };
            s.push_str(seg);
        }
        // No empty query on bases: ada drops it when resolving (the spec keeps it).
        let queries: &[&str] = match hierarchical {
            true => &["?a=1&b=2", "?q=a b", "?x=%zz&y", "?é=✓"],
            false => &["?", "?a=1&b=2", "?q=a b", "?x=%zz&y", "?é=✓"],
        };
        if self.rng.chance(40) {
            s.push_str(self.rng.pick(queries));
        }
        if self.rng.chance(30) {
            s.push_str(self.rng.pick(&["#", "#frag", "#a b", "#%41"]));
        }
        format!("\"{s}\"")
    }

    fn url_stmt(&mut self) -> (String, bool) {
        let text = |g: &mut StdGen| g.text(&TEXT_CHARS, 8);
        match self.rng.below(7) {
            0..=1 => (format!("showUrl(new URL({}));", self.url_text(false)), true),
            2 => {
                // No "": ada drops an empty base query ("http://h/p?") that the WHATWG parser
                // (and std/url) copy.
                let rel = *self.rng.pick(&[
                    "\"g\"",
                    "\"../x?y#z\"",
                    "\"//h/p\"",
                    "\"?q\"",
                    "\"#f\"",
                    "\"/a/./b/../c\"",
                ]);
                (
                    format!("showUrl(new URL({rel}, {}));", self.url_text(true)),
                    true,
                )
            }
            3 => {
                let prop = *self.rng.pick(&[
                    "protocol", "username", "password", "host", "hostname", "port", "pathname",
                    "search", "hash",
                ]);
                // Host setters ignore values with `/` or `?` (bug url-host-setter-delimiters).
                // Setters percent-encode tab/newline (bug url-setter-tab-newline): none here.
                // Userinfo without a lone `%`: ada's `href` drops it next to an escape while its
                // `username` keeps it.
                let base = self.url_text(prop.starts_with("host"));
                // A port only as `:81`: `file:` hosts can't have one (bug url-file-host-port)
                // and `"h:"` clears the port (bug url-host-setter-delimiters).
                let port = match !base.starts_with("\"file") && self.rng.chance(30) {
                    true => ":81",
                    false => "",
                };
                let value = match prop {
                    // Never an empty host before `:`, only on URLs that have a host (both
                    // mishandled: see the bug's golden).
                    "host" => {
                        let h = self.text(&HOST_CHARS, 5);
                        format!("\"h{}{port}\"", &h[1..h.len() - 1])
                    }
                    "hostname" => self.text(&HOST_CHARS, 5).replacen('"', "\"h", 1),
                    "username" | "password" => self.text(&USERINFO_CHARS, 5),
                    _ => self.text(&SETTER_CHARS, 5),
                };
                let body = format!("const u = new URL({base}); u.{prop} = {value}; showUrl(u);");
                (body, true)
            }
            4 => {
                // ASCII only: ada mis-decodes raw non-ASCII next to `%` escapes ("é%C3").
                let ascii = |g: &mut StdGen| g.text(&TEXT_CHARS[..17], 8);
                let q = ascii(self);
                let (k, v) = (ascii(self), ascii(self));
                let op = match self.rng.below(4) {
                    0 => format!("p.append({k}, {v});"),
                    1 => format!("p.set({k}, {v});"),
                    2 => format!("p.delete({k});"),
                    _ => "p.sort();".into(),
                };
                let body = format!(
                    "const p = new URLSearchParams({q}); {op} console.log(p.toString(), p.size, JSON.stringify([...p.keys()]), JSON.stringify([...p.values()]));"
                );
                (body, false)
            }
            5 => {
                let s = text(self);
                let body = format!("console.log(encodeURIComponent({s}), encodeURI({s}));");
                (body, false)
            }
            _ => {
                let f = *self.rng.pick(&["decodeURIComponent", "decodeURI"]);
                (format!("console.log({f}({}));", text(self)), true)
            }
        }
    }

    fn encoding_stmt(&mut self) -> String {
        const B64: [&str; 12] = [
            "A", "z", "0", "+", "/", "-", "_", "=", "Zm9v", "YQ", " ", "!",
        ];
        const HEX: [&str; 7] = ["0", "a", "F", "9", "g", "ff", "C3A9"];
        match self.rng.below(6) {
            0 => {
                let b = self.bytes(12);
                format!("const b: u8[] = {b}; console.log(base64Encode(b), base64UrlEncode(b), hexEncode(b));")
            }
            1 => {
                let f = *self.rng.pick(&["base64Decode", "base64UrlDecode"]);
                format!("console.log(JSON.stringify({f}({})));", self.text(&B64, 8))
            }
            2 => format!(
                "console.log(JSON.stringify(hexDecode({})));",
                self.text(&HEX, 6)
            ),
            3 => {
                let b = self.bytes(8);
                format!("const b: u8[] = {b}; console.log(utf8Valid(b), JSON.stringify(utf8DecodeLossy(b)), JSON.stringify(utf8Decode(b)));")
            }
            4 => {
                let s = self.text(&TEXT_CHARS, 8);
                format!("const e = base64EncodeString({s}); console.log(e, base64DecodeString(e) == {s}, JSON.stringify(utf8Encode({s})));")
            }
            _ => format!("console.log(base64DecodeString({}));", self.text(&B64, 8)),
        }
    }

    fn crypto_stmt(&mut self) -> String {
        match self.rng.below(3) {
            0 => {
                let s = self.text(&TEXT_CHARS, 12);
                format!("console.log(sha256Hex({s}), sha1Hex({s}));")
            }
            1 => {
                let (k, d) = (self.bytes(80), self.bytes(70));
                format!("const k: u8[] = {k}; const d: u8[] = {d}; console.log(hexEncode(hmacSha256(k, d)), hexEncode(hmacSha1(k, d)));")
            }
            _ => {
                let d = self.bytes(130);
                format!(
                    "const d: u8[] = {d}; console.log(hexEncode(sha256(d)), hexEncode(sha1(d)));"
                )
            }
        }
    }

    fn csv_stmt(&mut self) -> String {
        const CSV: [&str; 12] = [
            "a", "b1", ",", ",", "\\\"", "\\n", "\\r\\n", "\\r", " ", "\\t", ";", "\\\"\\\"",
        ];
        let opts = match self.rng.below(4) {
            0 => String::new(),
            1 => ", { delimiter: \";\" }".into(),
            2 => ", { trim: true }".into(),
            _ => ", { skipEmptyLines: true, trim: true }".into(),
        };
        if self.rng.chance(70) {
            let text = self.text(&CSV, 14);
            return format!("console.log(JSON.stringify(parseCsv({text}{opts})));");
        }
        let rows: Vec<String> = (0..self.rng.range(0, 3))
            .map(|_| {
                let fields: Vec<String> = (0..self.rng.range(1, 3))
                    .map(|_| self.text(&CSV, 4))
                    .collect();
                format!("[{}]", fields.join(", "))
            })
            .collect();
        let write = *self
            .rng
            .pick(&["", ", { crlf: true }", ", { delimiter: \";\" }"]);
        let read = if write.contains(';') {
            ", { delimiter: \";\" }"
        } else {
            ""
        };
        format!(
            "const rows: string[][] = [{}]; const t = stringifyCsv(rows{write}); console.log(JSON.stringify(t), JSON.stringify(parseCsv(t{read})) == JSON.stringify(rows));",
            rows.join(", ")
        )
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn deterministic_and_balanced() {
        for seed in 0..100 {
            let p = super::program(seed);
            assert_eq!(p, super::program(seed));
            assert_eq!(
                p.matches('{').count(),
                p.matches('}').count(),
                "seed {seed}:\n{p}"
            );
        }
    }
}
