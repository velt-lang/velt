const MAX = "i64::MAX";
function rs(s) {
  let o = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"') o += '\\"';
    else if (ch === "\\") o += "\\\\";
    else if (c >= 0x20 && c < 0x7f) o += ch;
    else o += "\\u{" + c.toString(16) + "}";
  }
  return o + '"';
}
const dv = new DataView(new ArrayBuffer(8));
function f(x) {
  if (Number.isNaN(x)) return "NAN";
  dv.setFloat64(0, x);
  return "0x" + dv.getBigUint64(0).toString(16).padStart(16, "0");
}
function i(x) { return x === MAX ? MAX : String(x); }
const out = [];
out.push("//! Expected results generated by a real JS engine (node 22) with");
out.push("//! crates/velt_rt/scripts/gen_str_table.js (then `cargo fmt`); regenerate instead of editing.");
out.push("//! Floats are bit patterns (`NAN` = any NaN). String inputs of index-based cases are ASCII,");
out.push("//! where byte offsets and UTF-16 indexes agree.");
out.push("");
out.push("pub const NAN: u64 = u64::MAX;");
function table(name, ty, rows) {
  out.push(`pub const ${name}: &[${ty}] = &[`);
  for (const r of rows) out.push(`    (${r.join(", ")}),`);
  out.push("];");
}

