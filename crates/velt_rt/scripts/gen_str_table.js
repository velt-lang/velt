// Generates crates/velt_rt/tests/abi/js_table.rs from a real JS engine (node):`n//   node crates/velt_rt/scripts/gen_str_table.js > crates/velt_rt/tests/abi/js_table.rs
const MAX = "i64::MAX";
function rs(s) {
  let o = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"') o += '\\"';
    else if (ch === "\\") o += "\\\\";
    else if (c >= 0x20 && c < 0x7f) o += ch;
    else o += "\\u{" + c.toString(16) + "}";
  }
  return o + '"';
}
function i(x) { return x === MAX ? MAX : String(x); }
const out = [];
out.push("//! Expected results generated by a real JS engine (node 22) with");
out.push("//! crates/velt_rt/scripts/gen_str_table.js (then `cargo fmt`); regenerate instead of editing.");
out.push("//! String inputs of index-based cases are ASCII, where byte offsets and UTF-16 indexes agree.");
out.push("");
function table(name, ty, rows) {
  out.push(`pub const ${name}: &[${ty}] = &[`);
  for (const r of rows) out.push(`    (${r.join(", ")}),`);
  out.push("];");
}

// slice is Velt code (#2816), and `Number(s)` (tests/golden/lang/any_string_to_number.velt,
// #2196); indexOf, lastIndexOf, includes, startsWith and endsWith are Velt code (#2198): their cases are
// tests/golden/lang/string_search.velt.
// split, trim, replace, repeat and padStart / padEnd too: tests/golden/lang/
// string_methods_node_table.velt.

const cases = ["hello", "Straße", "ǅ", "ΑΣ ΟΔΟΣ", "İstanbul", "ﬁ", "ŉ", "ΐ", "Σ", "aΣ", "ÀÉÎ", "ǆ",
  "MiXeD 123", "", "ὈΔΥΣΣΕΎΣ", "ǰ", "Ωmega", "ß"];
table("CASE", "(&str, &str, &str)", cases.map(s => [rs(s), rs(s.toUpperCase()), rs(s.toLowerCase())]));

table("CHAR_CODE_AT", "(&str, i64, i64)", [-1, 0, 1, 2, 3].map(k => {
  const c = "Az~".charCodeAt(k);
  return [rs("Az~"), String(k), String(Number.isNaN(c) ? -1 : c)];
}));

const codes = [65, 0, 127, 128, 233, 0x20ac, 0xd800, 0xdc00, 65601, -1, 0xfffd, 65536 + 65, 4294967296 + 97];
table("FROM_CHAR_CODE", "(i64, &str)", codes.map(c => [String(c), rs(String.fromCharCode(c).toWellFormed())]));

process.stdout.write(out.join("\n") + "\n");
