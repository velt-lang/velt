/// The type package's files for std's `inputs` (as [`crate::inputs_from_dir`] reads them with
/// the prefix `std`): `(path in the package, text)`, sorted by path.
pub fn type_package(inputs: &[Input], version: &str) -> Vec<(String, String)> {
    let widened = widen::widened(inputs);
    let mut modules: Vec<DocModule> = inputs
        .iter()
        .map(|i| {
            let stem = i.file.rsplit('/').next().unwrap_or("");
            DocModule {
                index: stem.split('.').next() == Some("index"),
                ..crate::extract::extract_widened(&i.module, &i.source, &widened)
            }
        })
        .collect();
    crate::resolve::resolve(&mut modules);
    let files: Vec<&str> = inputs.iter().map(|i| i.file.as_str()).collect();
    let package = Package::new(&modules, &files);
    let mut out: BTreeMap<String, String> = BTreeMap::new();
    let mut exports = vec![];
    for &m in &package.public {
        let rel = rel_of(&modules[m].name);
        out.insert(format!("{rel}/index.d.ts"), package.module_file(m));
        exports.push(rel);
    }
    out.insert("globals.d.ts".into(), package.globals_file());
    out.insert("package.json".into(), package_json(&exports, version));
    out.insert("README.md".into(), README.into());
    out.into_iter().collect()
}

const README: &str = "# velt\n\nTypeScript declarations of the Velt standard library \
(https://github.com/velt-lang/velt), generated by `velt doc --types`: with this package \
installed, `tsc` and editors resolve `import type { … } from \"velt/<module>\"`. It holds \
declarations only; the modules run in Velt.\n";

/// `package.json`: the package `velt`, a `types` entry per public module.
fn package_json(exports: &[&str], version: &str) -> String {
    let mut out = format!(
        "{{\n  \"name\": \"velt\",\n  \"version\": \"{version}\",\n  \"description\": \"TypeScript \
         declarations of the Velt standard library\",\n  \"license\": \"MIT OR Apache-2.0\",\n  \
         \"exports\": {{\n"
    );
    let entries: Vec<String> = exports
        .iter()
        .map(|rel| format!("    \"./{rel}\": {{ \"types\": \"./{rel}/index.d.ts\" }}"))
        .collect();
    out.push_str(&entries.join(",\n"));
    out.push_str("\n  }\n}\n");
    out
}

/// `std/net/http` → `net/http`.
fn rel_of(module: &str) -> &str {
    module
        .strip_prefix(std_modules::CANONICAL_PREFIX)
        .unwrap_or(module)
}

/// Where a declaration is: its module's index and its declared name there.
type DeclAt = (usize, String);

struct Package<'a> {
    modules: &'a [DocModule],
    files: &'a [&'a str],
    index: ModuleIndex,
    /// The public modules, sorted by name.
    public: Vec<usize>,
    /// The prelude's and `lang/`'s files: their exports are globals (not the intrinsics' files,
    /// whose exports only std imports).
    global_files: Vec<usize>,
    /// Each declaration's public exports: `(public module, exported name)`, sorted.
    exported_as: HashMap<DeclAt, Vec<(usize, String)>>,
    /// Each module's own declarations by name (exported ones; extensions left out).
    own: Vec<HashMap<String, &'a DocItem>>,
}

impl<'a> Package<'a> {
    fn new(modules: &'a [DocModule], files: &'a [&'a str]) -> Package<'a> {
        let index = ModuleIndex::new(modules);
        let mut public: Vec<usize> = (0..modules.len())
            .filter(|&m| files[m].ends_with("/index.vlt") && std_modules::importable(files[m]))
            .collect();
        public.sort_by(|&a, &b| modules[a].name.cmp(&modules[b].name));
        let intrinsics = velt_common::std_dir!(lang_intrinsics)
            .strip_prefix(std_modules::CANONICAL_PREFIX)
            .unwrap_or_default();
        let global_files: Vec<usize> = (0..modules.len())
            .filter(|&m| files[m].starts_with("prelude/") || files[m].starts_with("lang/"))
            .filter(|&m| !files[m].starts_with(intrinsics))
            .collect();
        let own: Vec<HashMap<String, &DocItem>> = modules
            .iter()
            .map(|m| {
                m.items
                    .iter()
                    .filter(|it| it.origin.is_none() && !it.ts.text.is_empty())
                    .filter(|it| it.kind != Kind::Extension)
                    .map(|it| (it.ts.name.clone(), it))
                    .collect()
            })
            .collect();
        let mut package = Package {
            modules,
            files,
            index,
            public,
            global_files,
            exported_as: HashMap::new(),
            own,
        };
        for &m in &package.public.clone() {
            for it in &modules[m].items {
                if let Some(at) = package.decl_of(m, it) {
                    package
                        .exported_as
                        .entry(at)
                        .or_default()
                        .push((m, it.name.clone()));
                }
            }
        }
        package
    }

    /// Where item `it`, exported by module `m`, is declared.
    fn decl_of(&self, m: usize, it: &DocItem) -> Option<DeclAt> {
        if matches!(it.kind, Kind::Extension | Kind::ReExport) {
            return None;
        }
        match &it.origin {
            None => Some((m, it.ts.name.clone())),
            Some(o) => {
                let at = *self.index_of(&o.module)?;
                let decl = self.own[at].get(&o.name)?;
                Some((at, decl.ts.name.clone()))
            }
        }
    }

    fn index_of(&self, name: &str) -> Option<&usize> {
        self.index.names().get(name)
    }

    /// The public module that declares what is at `at`: the owner of its source file when that
    /// exports it, else the first public module that does.
    fn home(&self, at: &DeclAt) -> Option<(usize, String)> {
        let exports = self.exported_as.get(at)?;
        let owner = std_modules::owner(self.files[at.0], &|dir| {
            self.index_of(&format!("{}{dir}", std_modules::CANONICAL_PREFIX))
                .is_some()
        });
        let owner = owner.map(|dir| format!("{}{dir}", std_modules::CANONICAL_PREFIX));
        exports
            .iter()
            .find(|(m, _)| Some(&self.modules[*m].name) == owner.as_ref())
            .or_else(|| exports.first())
            .cloned()
    }

    /// What type name `name`, written in module `from`, refers to: the declaration `from`
    /// makes, an import names or the prelude makes. `None` for TypeScript's globals and names
    /// that are not found.
    fn resolve_ref(&self, from: usize, name: &str) -> Option<DeclAt> {
        if let Some(it) = self.own[from].get(name) {
            return Some((from, it.ts.name.clone()));
        }
        let Some(import) = self.modules[from].imports.iter().find(|i| i.local == name) else {
            // The prelude's names are seen everywhere.
            return self
                .global_files
                .iter()
                .find_map(|&g| self.own[g].get(name).map(|it| (g, it.ts.name.clone())));
        };
        let target = self.index.resolve(&self.modules[from].name, &import.from)?;
        let exported = import.name.as_ref()?;
        let it = self.modules[target]
            .items
            .iter()
            .find(|it| &it.name == exported)?;
        self.decl_of(target, it)
    }

    /// The `index.d.ts` of public module `m`.
    fn module_file(&self, m: usize) -> String {
        let mut file = DeclFile::new(self, Some(m));
        for it in &self.modules[m].items {
            let Some(at) = self.decl_of(m, it) else {
                continue;
            };
            match self.home(&at) {
                Some((home, name)) if home != m => {
                    let spec = std_modules::specifier(&self.modules[home].name).unwrap_or_default();
                    file.reexports.push(format!(
                        "export {{ {} }} from \"{spec}\";",
                        rename(&name, &it.name)
                    ));
                }
                _ => file.declare(&at, &it.name, true),
            }
        }
        file.extensions(|f| self.owner_of(f) == Some(m));
        file.finish()
    }

    /// `globals.d.ts`: the prelude's declarations TypeScript lacks, exported, with the
    /// extensions of those types.
    fn globals_file(&self) -> String {
        let mut file = DeclFile::new(self, None);
        for &g in &self.global_files {
            let mut names: Vec<&String> = self.own[g].keys().collect();
            names.sort();
            for name in names {
                if !TS_GLOBALS.contains(&name.as_str()) {
                    file.declare(&(g, name.clone()), name, true);
                }
            }
        }
        file.extensions(|f| self.owner_of(f).is_none());
        file.finish()
    }

    /// The public module that owns file `f`; `None` in `prelude/`, `lang/` and outside modules.
    fn owner_of(&self, f: usize) -> Option<usize> {
        let dir = std_modules::owner(self.files[f], &|dir| {
            self.index_of(&format!("{}{dir}", std_modules::CANONICAL_PREFIX))
                .is_some()
        })?;
        let m = *self.index_of(&format!("{}{dir}", std_modules::CANONICAL_PREFIX))?;
        self.public.contains(&m).then_some(m)
    }
}
