//! The generated root module of a test program: it imports the test files and registers their
//! tests with `velt/test` (`std/test/registry.vlt`, `std/test/run.vlt`), which runs them. For `math.test.vlt` and
//! `io.test.vlt` it is (a virtual file in a directory above both)
//! ```text
//! import { registerFile, registerTest, registerAsyncTest } from "velt/test/registry";
//! import { runRegistered } from "velt/test/run";
//! import * as __velt_t0 from "./math.test.vlt";
//! import * as __velt_t1 from "./io.test.vlt";
//! function __velt_r0() {
//!   registerFile(0);
//!   registerTest("test_add", __velt_t0.test_add);
//! }
//! function __velt_r1() {
//!   registerFile(2);
//!   registerAsyncTest("test_read", __velt_t1.test_read);
//! }
//! async function main() {
//!   __velt_r0();
//!   __velt_r1();
//!   await runRegistered();
//! }
//! ```
//! `registerFile(n)` gives the file the next `n` registrations its top level queued (`io.test.vlt` has
//! two top-level `describe` or `it` calls): the test files are evaluated in import order, before
//! `main`. A file alone in its harness takes them all (`-1`), whatever its top level does.
//! A function per file keeps `main` small whatever the number of tests: an `async` function's
//! lowering (saving its locals across `await`s) grows with the square of its size, and a `main`
//! registering 1,000 tests took seconds to compile.
//! Everything else (choosing the file a process runs, running and reporting the tests, starting
//! processes) is `velt/test`'s.

use std::fmt::Write;

/// The variable naming the plan of a run (`velt/test`'s `Plan`, as JSON in this file).
pub const PLAN_VAR: &str = "VELT_TEST_PLAN";

/// Variables `velt/test` reads that a run's runner must not inherit.
pub const CHILD_VARS: [&str; 5] = [
    "VELT_TEST_FILE",
    "VELT_TEST_FROM",
    "VELT_TEST_MARK",
    "VELT_TEST_FILTER",
    "VELT_TEST_EXACT",
];

/// One test file of a harness.
pub struct HarnessFile<'a> {
    /// How the harness imports it (`./tests/math.test.vlt`).
    pub import_spec: String,
    /// Its tests, in the order they run.
    pub tests: &'a [String],
    /// Those of `tests` that are `async`.
    pub async_tests: &'a [String],
    /// How many registrations its top level queues; `None`: all there are.
    pub queued: Option<usize>,
}

/// Velt source of a harness registering the tests of `files`, in order.
pub fn harness_source(files: &[HarnessFile]) -> String {
    // The runner's hooks (velt_common `std_hooks.rs`), from velt/test's internal files, which
    // the loader lets only the harness import (`LoadOptions::test_harness`).
    use velt_common::std_hook_name as hook;
    let mut src = String::from(concat!(
        "// Generated by `velt test`.\nimport { ",
        velt_common::std_hook_name!(register_file),
        ", ",
        velt_common::std_hook_name!(register_test),
        ", ",
        velt_common::std_hook_name!(register_async_test),
        " } from \"",
        velt_common::std_specifier!(test_registry),
        "\";\nimport { ",
        velt_common::std_hook_name!(run_registered),
        " } from \"",
        velt_common::std_specifier!(test_run),
        "\";\n",
    ));
    for (i, f) in files.iter().enumerate() {
        let _ = writeln!(src, "import * as __velt_t{i} from \"{}\";", f.import_spec);
    }
    for (i, f) in files.iter().enumerate() {
        let queued = f.queued.map_or(-1, |n| n as i64);
        let file = hook!(register_file);
        let _ = writeln!(src, "\nfunction __velt_r{i}() {{\n  {file}({queued});");
        for t in f.tests {
            let register = match f.async_tests.contains(t) {
                true => hook!(register_async_test),
                false => hook!(register_test),
            };
            let _ = writeln!(src, "  {register}(\"{t}\", __velt_t{i}.{t});");
        }
        src.push_str("}\n");
    }
    src.push_str("\nasync function main() {\n");
    for i in 0..files.len() {
        let _ = writeln!(src, "  __velt_r{i}();");
    }
    let _ = writeln!(src, "  await {}();\n}}", hook!(run_registered));
    src
}

#[cfg(test)]
mod tests {
    use super::*;

    fn names(n: &[&str]) -> Vec<String> {
        n.iter().map(|s| s.to_string()).collect()
    }

    fn file<'a>(spec: &str, tests: &'a [String], async_tests: &'a [String]) -> HarnessFile<'a> {
        HarnessFile {
            import_spec: spec.to_string(),
            tests,
            async_tests,
            queued: Some(0),
        }
    }

    #[test]
    fn registers_each_files_tests_in_order() {
        let (a, b, b_async) = (
            names(&["test_x", "test_y"]),
            names(&["test_x", "test_z"]),
            names(&["test_z"]),
        );
        let src = harness_source(&[
            file("./a.test.vlt", &a, &[]),
            HarnessFile {
                queued: Some(2),
                ..file("./sub/b.test.ts", &b, &b_async)
            },
        ]);
        assert!(
            src.contains("import * as __velt_t1 from \"./sub/b.test.ts\";"),
            "{src}"
        );
        // The same test name in two files: each is reached through its own namespace.
        let want = "function __velt_r0() {\n  registerFile(0);\n  \
                    registerTest(\"test_x\", __velt_t0.test_x);\n  \
                    registerTest(\"test_y\", __velt_t0.test_y);\n}\n\n\
                    function __velt_r1() {\n  registerFile(2);\n  \
                    registerTest(\"test_x\", __velt_t1.test_x);\n  \
                    registerAsyncTest(\"test_z\", __velt_t1.test_z);\n}\n\n\
                    async function main() {\n  __velt_r0();\n  __velt_r1();\n  \
                    await runRegistered();\n}\n";
        assert!(src.ends_with(want), "{src}");
        let (_, diags) = velt_syntax::parse_file(velt_common::FileId(0), &src);
        assert!(diags.is_empty(), "{diags:?}\n{src}");
    }

    #[test]
    fn a_harness_without_files_still_runs() {
        let src = harness_source(&[]);
        assert!(src.contains("await runRegistered();"), "{src}");
        let (_, diags) = velt_syntax::parse_file(velt_common::FileId(0), &src);
        assert!(diags.is_empty(), "{diags:?}");
    }
}
