//! The generated test harness and reading its output.
//!
//! One harness runs the tests of one or more test files. For `math.test.vlt` and
//! `io.test.vlt` it is a root module (a virtual file in a directory above both) like
//! ```text
//! import * as __velt_t0 from "./math.test.vlt";
//! import * as __velt_t1 from "./io.test.vlt";
//! function __velt_run0(from: number) {
//!   if (from <= 0) {
//!     __velt_t0.test_add();
//!     console.log("::velt-test-ok:: test_add");
//!   }
//!   ...
//! }
//! async function __velt_run1(from: number) { ... await __velt_t1.test_read(); ... }
//! async function main() {
//!   const file = process.env.VELT_TEST_FILE ?? "all";
//!   const from = Number(process.env.VELT_TEST_FROM ?? "0");
//!   if (file == "all" || file == "0") { __velt_run0(from); }
//!   if (file == "all" || file == "1") { await __velt_run1(from); }
//! }
//! ```
//! The runner starts the harness once per file ([`FILE_VAR`]), so each file has a process of its
//! own, as it had with a harness per file; started without it, the harness runs every file.
//! A failing `assert` panics (or a test throws), which ends the process: the test after the last
//! marker line is the one that failed. The runner then starts the same harness again with
//! [`FROM_VAR`] set to the test after it, so one failure does not hide the others and costs no
//! rebuild.

use std::fmt::Write;

/// Prefix of the line the harness prints after each passing test.
pub const OK_MARKER: &str = "::velt-test-ok:: ";

/// The variable naming the file (its index in the harness) whose tests a harness runs.
pub const FILE_VAR: &str = "VELT_TEST_FILE";

/// The variable naming the first of the file's tests (an index) that a harness runs.
pub const FROM_VAR: &str = "VELT_TEST_FROM";

/// One test file of a harness.
pub struct HarnessFile<'a> {
    /// How the harness imports it (`./tests/math.test.vlt`).
    pub import_spec: String,
    /// Its tests, in the order they run.
    pub tests: &'a [String],
    /// Those of `tests` that are `async`.
    pub async_tests: &'a [String],
}

/// Velt source of a harness running the tests of `files`.
pub fn harness_source(files: &[HarnessFile]) -> String {
    let mut src = String::from("// Generated by `velt test`.\n");
    for (i, f) in files.iter().enumerate() {
        let _ = writeln!(src, "import * as __velt_t{i} from \"{}\";", f.import_spec);
    }
    let is_async = |f: &HarnessFile| f.tests.iter().any(|t| f.async_tests.contains(t));
    for (i, f) in files.iter().enumerate() {
        let kw = if is_async(f) { "async " } else { "" };
        let _ = writeln!(src, "\n{kw}function __velt_run{i}(from: number) {{");
        for (n, t) in f.tests.iter().enumerate() {
            let call = if f.async_tests.contains(t) {
                "await "
            } else {
                ""
            };
            let _ = writeln!(
                src,
                "  if (from <= {n}) {{\n    {call}__velt_t{i}.{t}();\n    \
                 console.log(\"{OK_MARKER}{t}\");\n  }}"
            );
        }
        src.push_str("}\n");
    }
    let kw = if files.iter().any(is_async) {
        "async "
    } else {
        ""
    };
    let _ = writeln!(
        src,
        "\n{kw}function main() {{\n  const file = process.env.{FILE_VAR} ?? \"all\";\n  \
         const from = Number(process.env.{FROM_VAR} ?? \"0\");"
    );
    for (i, f) in files.iter().enumerate() {
        let call = if is_async(f) { "await " } else { "" };
        let _ = writeln!(
            src,
            "  if (file == \"all\" || file == \"{i}\") {{\n    {call}__velt_run{i}(from);\n  }}"
        );
    }
    src.push_str("}\n");
    src
}

/// One harness run, read back.
#[derive(Debug, PartialEq, Eq)]
pub struct RunOutput {
    /// How many of the tests (a prefix of the list) passed.
    pub passed: usize,
    /// Stdout with marker lines replaced by `ok <name>` (test output stays interleaved).
    pub display: Vec<String>,
}

/// Interpret harness stdout for `tests` (in harness order).
pub fn read_output(stdout: &str, tests: &[String]) -> RunOutput {
    let mut passed = 0;
    let mut display = vec![];
    for line in stdout.lines() {
        match line.strip_prefix(OK_MARKER) {
            Some(name) if tests.get(passed).is_some_and(|t| t == name) => {
                passed += 1;
                display.push(format!("ok {name}"));
            }
            _ => display.push(line.to_string()),
        }
    }
    RunOutput { passed, display }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn names(n: &[&str]) -> Vec<String> {
        n.iter().map(|s| s.to_string()).collect()
    }

    fn file<'a>(spec: &str, tests: &'a [String], async_tests: &'a [String]) -> HarnessFile<'a> {
        HarnessFile {
            import_spec: spec.to_string(),
            tests,
            async_tests,
        }
    }

    #[test]
    fn generates_imports_and_calls_in_order() {
        let tests = names(&["test_add", "test_sub"]);
        let src = harness_source(&[file("./math.test.vlt", &tests, &[])]);
        assert!(
            src.contains("import * as __velt_t0 from \"./math.test.vlt\";"),
            "{src}"
        );
        let add = src.find("__velt_t0.test_add();").unwrap();
        let sub = src.find("__velt_t0.test_sub();").unwrap();
        assert!(add < sub);
        assert!(src.contains("console.log(\"::velt-test-ok:: test_add\");"));
        assert!(src.contains("if (from <= 1) {"), "{src}");
        assert!(src.contains("\nfunction main()"), "{src}");
    }

    #[test]
    fn one_harness_runs_several_files_by_index() {
        let (a, b, b_async) = (
            names(&["test_x"]),
            names(&["test_x", "test_y"]),
            names(&["test_y"]),
        );
        let src = harness_source(&[
            file("./a.test.vlt", &a, &[]),
            file("./sub/b.test.ts", &b, &b_async),
        ]);
        // The same test name in two files: each is reached through its own namespace.
        assert!(src.contains("__velt_t0.test_x();") && src.contains("__velt_t1.test_x();"));
        assert!(
            src.contains("\nfunction __velt_run0(") && src.contains("async function __velt_run1(")
        );
        assert!(src.contains("await __velt_t1.test_y();"), "{src}");
        assert!(src.contains("async function main()"), "{src}");
        assert!(
            src.contains("file == \"1\") {\n    await __velt_run1(from);"),
            "{src}"
        );
        assert!(src.contains(&format!("process.env.{FILE_VAR}")), "{src}");
        let (_, diags) = velt_syntax::parse_file(velt_common::FileId(0), &src);
        assert!(diags.is_empty(), "{diags:?}\n{src}");
    }

    #[test]
    fn harness_parses() {
        let tests = names(&["test_a"]);
        let src = harness_source(&[file("./x.test.vlt", &tests, &tests)]);
        let (_, diags) = velt_syntax::parse_file(velt_common::FileId(0), &src);
        assert!(diags.is_empty(), "{diags:?}");
    }

    #[test]
    fn reads_markers_and_keeps_test_output() {
        let tests = names(&["test_a", "test_b", "test_c"]);
        let out = read_output("hello\n::velt-test-ok:: test_a\nfrom b\n", &tests);
        assert_eq!(out.passed, 1);
        assert_eq!(out.display, ["hello", "ok test_a", "from b"]);
        // A stray marker for the wrong test is just output.
        assert_eq!(read_output("::velt-test-ok:: test_c\n", &tests).passed, 0);
    }
}
