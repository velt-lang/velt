//! Source generators in packages (docs/internals/design/source-generators.md §5): a package
//! declares a generated function whose generator is one of its own modules, and a program names
//! a generator module of a dependency by the package's specifier, as it would import it.

use std::path::{Path, PathBuf};

mod no_window;
mod test_dir;

const GENERATOR: &str = "import { Request, Output } from \"velt/generate\";\n\
     export function fields(req: Request, out: Output): void {\n\
     \x20 const t = req.model.type(req.args[0]);\n\
     \x20 const names: string[] = [];\n\
     \x20 for (const f of t.fields) { names.push(f.name); }\n\
     \x20 out.line(`return ${out.literal(t.display + \": \" + names.join(\",\"))};`);\n\
     }\n";

fn write(dir: &Path, rel: &str, text: &str) {
    let path = dir.join(rel);
    std::fs::create_dir_all(path.parent().expect("parent")).expect("dir");
    std::fs::write(path, text).expect("write");
}

/// A workspace: `packages/gens` declares `fields<T>()` (its generator `./gen` is its own module)
/// and `apps/app` uses it.
fn workspace() -> (test_dir::TestDir, PathBuf) {
    let tmp = test_dir::TestDir::new();
    let dir = tmp.path().to_path_buf();
    write(
        &dir,
        "velt.workspace.vlt",
        "export const workspace: Workspace = { members: [\"packages/*\", \"apps/*\"] };\n",
    );
    write(
        &dir,
        "packages/gens/package.vlt",
        "export const pkg: Package = { name: \"gens\", version: \"0.1.0\" };\n",
    );
    write(
        &dir,
        "packages/gens/src/lib.vlt",
        "export declare generated(\"./gen\") function fields<T>(): string;\n",
    );
    write(&dir, "packages/gens/src/gen.vlt", GENERATOR);
    write(
        &dir,
        "apps/app/package.vlt",
        "export const pkg: Package = { name: \"app\", version: \"0.1.0\", \
         dependencies: { gens: \"workspace\" } };\n",
    );
    write(
        &dir,
        "apps/app/src/main.vlt",
        "import { fields } from \"gens\";\n\
         class User { name = \"\"; age = 0; }\n\
         console.log(fields<User>());\n",
    );
    (tmp, dir)
}

#[test]
fn generators_come_from_packages() {
    let (_tmp, dir) = workspace();
    let run = |cwd: &Path| {
        let out = no_window::command(env!("CARGO_BIN_EXE_velt"))
            .args(["run", "src/main.vlt"])
            .current_dir(cwd)
            .env("VELT_HOME", dir.join("home"))
            .env("VELT_BUILD_CACHE", dir.join("cache"))
            .env_remove("VELT_REGISTRY")
            .output()
            .expect("run velt");
        let err = String::from_utf8_lossy(&out.stderr).into_owned();
        assert!(out.status.success(), "{err}");
        String::from_utf8_lossy(&out.stdout).into_owned()
    };
    let app = dir.join("apps/app");
    assert_eq!(run(&app), "User: name,age\n");
    // The program's own generated function, generated by the package's module (named
    // `fields`: the generator module exports a function of the declaration's name).
    write(
        &dir,
        "apps/app/src/main.vlt",
        "declare generated(\"gens/gen\") function fields<T>(): string;\n\
         class Team { size = 2; }\n\
         console.log(fields<Team>());\n",
    );
    assert_eq!(run(&app), "Team: size\n");
}
